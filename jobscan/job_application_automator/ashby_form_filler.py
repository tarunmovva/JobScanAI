HELP_TEXT = """Ashby form filler

Usage:
  python -m job_application_automator.ashby_form_filler <payload.json> [output_dir]

Arguments:
  payload.json  Edited fill_payload.json generated by ashby_form_extractor.py.
  output_dir    Optional directory for fill_result.json and screenshots.

Behavior:
  Opens the Ashby application in the shared Chrome CDP profile, uploads files, fills fields,
  pauses for CAPTCHA when required, submits, and leaves the tab open if CAPTCHA blocks submission.
"""


NAV_TIMEOUT = 25_000
RENDER_WAIT = 4_500
FIELD_DELAY = 150


def _write_result(output_dir: Path, result: dict) -> None:
    out_file = output_dir / "fill_result.json"
    out_file.write_text(json.dumps(result, indent=2, ensure_ascii=False), encoding="utf-8")


async def fill(payload_path: Path, output_dir: Path) -> dict:
    """Crash guard: any unhandled exception still writes fill_result.json so
    Go/Electron always find a submission status (mirrors greenhouse)."""
    try:
        return await _fill_inner(payload_path, output_dir)
    except Exception as exc:
        reason = f"{type(exc).__name__}: {exc}"
        result = {
            "platform": "ashby",
            "apply_url": "",
            "filled_at": datetime.now().isoformat(timespec="seconds"),
            "filled": [], "skipped": [],
            "errors": [{"id": "_fatal", "error": reason}],
            "submission": {"status": "error", "reason": reason},
            "tab_left_open": False,
        }
        try:
            result["apply_url"] = json.loads(payload_path.read_text(encoding="utf-8")).get("apply_url", "")
        except Exception:
            pass
        _write_result(output_dir, result)
        print(f"Fatal filler error — wrote error result: {reason}", file=sys.stderr)
        return result


async def _fill_inner(payload_path: Path, output_dir: Path) -> dict:
    log = FillLog("ashby", job_ref_from(payload_path), output_dir)
    payload = json.loads(payload_path.read_text(encoding="utf-8"))
    apply_url: str = payload["apply_url"]
    # Turn the letter into whatever this form accepts BEFORE binding answers:
    # injection installs a new dict when the payload had none, so binding
    # afterwards always names the dict that actually got filled.
    _cover_fields = inject_cover_letter(payload, output_dir)
    answers: dict = payload.get("answers", {})

    result = {
        "platform": "ashby",
        "apply_url": apply_url,
        "filled_at": datetime.now().isoformat(timespec="seconds"),
        "filled": [],
        "skipped": [],
        "errors": [],
    }

    async with async_playwright() as pw, close_tab_on_unattended_crash() as tab_guard:
        session = await open_cdp_page(
            pw, viewport={"width": 1366, "height": 900},
            tab_stage="fill",
            tab_text=tab_tag.tab_text(
                (payload.get("job_context") or {}).get("company") or "",
                (payload.get("job_context") or {}).get("title") or "",
            ),
        )
        tab_guard.watch(session)
        page = session.page
        # Record the POST that files the application. Ashby submits through
        # graphql, which answers HTTP 200 even when it rejects, so the body is
        # inspected too. Used only as an EXTRA positive signal, and written into
        # fill_result.json so the real endpoint shapes become visible.
        network_responses: list[dict] = []
        attach_response_recorder(page, network_responses)
        result["network"] = network_responses

        log("nav.start", url=apply_url)
        try:
            await page.goto(apply_url, wait_until="domcontentloaded", timeout=NAV_TIMEOUT)
            log("nav.done", elapsed_s=log.elapsed_s())
        except Exception as exc:
            result["errors"].append(f"navigate: {exc}")
            # Broken failure — no page to complete manually; close and record.
            log("nav.failed", err=str(exc))
            result["submission"] = {"status": "nav_failed", "reason": f"navigate: {exc}"}
            result["tab_left_open"] = False
            await session.cleanup()
            _write_result(output_dir, result)
            return result

        await page.wait_for_timeout(RENDER_WAIT)

        # Scroll to bottom to trigger lazy-rendered fields, then back to top
        await page.evaluate("window.scrollTo(0, document.body.scrollHeight)")
        await page.wait_for_timeout(1500)
        await page.evaluate("window.scrollTo(0, 0)")
        await page.wait_for_timeout(500)

        fields = _load_extracted_fields(payload_path)

        # Pass 1: upload resume first, wait for analysis
        for field_id, value in answers.items():
            if value == "" or value is None:
                continue
            field_def = fields.get(field_id, {})
            ftype = field_def.get("type") or _guess_type(field_id, value)
            if ftype != "file":
                continue
            selector = field_def.get("selector", "")
            ok, err = await _fill_field(page, field_id, ftype, value, selector, field_def)
            log("fill.field", id=field_id, type=ftype, ok=ok, err=None if ok else err)
            if ok:
                result["filled"].append(field_id)
                await _wait_for_resume_analysis(page)
            else:
                result["errors"].append({"id": field_id, "error": err})

        # Screenshot after resume upload
        try:
            ts = datetime.now().strftime("%H%M%S")
            await page.screenshot(path=str(output_dir / f"filled_{ts}.png"), full_page=True)
        except Exception:
            pass

        # Pause for CAPTCHA BEFORE filling other fields.
        # Only pause if running interactively (terminal). When called from a subprocess
        # (app/CI), Ashby does not show CAPTCHA — skip the pause entirely.
        import sys as _sys
        if _sys.stdin.isatty():
            print("\n=== CAPTCHA ===")
            print("Solve the CAPTCHA in the browser, then press ENTER here to fill + submit.")
            try:
                await asyncio.get_event_loop().run_in_executor(None, input)
            except Exception:
                pass
        else:
            # Non-interactive: Ashby has no CAPTCHA, continue immediately
            await asyncio.sleep(0.5)

        # Pass 2: fill all non-file fields AFTER CAPTCHA (no re-render gap before submit)
        for field_id, value in answers.items():
            if value == "" or value is None:
                result["skipped"].append({"id": field_id, "reason": "empty value"})
                log("skip", id=field_id, reason="empty value")
                continue

            field_def = fields.get(field_id, {})
            ftype = field_def.get("type") or _guess_type(field_id, value)
            if ftype == "file":
                continue  # already done in pass 1
            selector = field_def.get("selector", "")

            ok, err = await _fill_field(page, field_id, ftype, value, selector, field_def)
            log("fill.field", id=field_id, type=ftype, ok=ok, err=None if ok else err)
            if ok:
                result["filled"].append(field_id)
                if err:
                    # A successful fill can still carry a diagnostic. Two very
                    # different populations share this slot: benign confirmations
                    # ("selected option: Birmingham, Alabama, United States") and
                    # genuine degradation ("typed value, no dropdown option
                    # selected"). Both used to be appended to errors[] under a
                    # "note" key, which put a SUCCESS into the list that feeds the
                    # recovery dossier and the user's "Fill issues" section — 12 of
                    # them in one 15-job run, every single one a success.
                    if _is_degraded_fill(err):
                        result["errors"].append({"id": field_id, "error": err, "degraded": True})
                    else:
                        result.setdefault("notes", []).append({"id": field_id, "note": err})
            else:
                result["errors"].append({"id": field_id, "error": err})

            await page.wait_for_timeout(FIELD_DELAY)

        # In-session verification (while form is filled)
        verify = await _verify_filled(page, fields, answers)
        result["verification"] = verify
        _print_verify(verify)
        failed_checks = [c for c in verify["checks"] if not c["pass"]]
        log("verify.done", checks=len(verify["checks"]), failed=len(failed_checks))
        for c in failed_checks:
            log("verify.fail", id=c.get("id"), expected=c.get("expected"), actual=c.get("actual"))

        # Screenshot after fill
        try:
            ts = datetime.now().strftime("%H%M%S")
            await page.screenshot(path=str(output_dir / f"filled_{ts}.png"), full_page=True)
        except Exception:
            pass

        # Submit with a trusted browser click first; JS submit is only a fallback.
        if failed_checks:
            submission = {
                "status": "verification_failed",
                "reason": f"{len(failed_checks)} field value checks failed before submit",
            }
            result["submission"] = submission
            result["errors"].append({
                "id": "_verification",
                "error": submission["reason"],
            })
            print(f"Submission skipped: {submission['reason']}")
            try:
                await page.screenshot(path=str(output_dir / "verification_failed.png"), full_page=True)
            except Exception:
                pass

            # AI recovery: hand the live tab to an agent to fix the mismatched
            # fields and submit; only a detector-confirmed submit counts.
            baseline_state = await _capture_application_state(page)

            async def _recovery_detect() -> bool:
                detected = await _detect_submission_state(page, True, baseline_state, network_responses)
                return detected.get("status") == "submitted"

            recovered = await attempt_recovery(
                platform="ashby", apply_url=apply_url, payload=payload,
                result=result, output_dir=output_dir,
                failure={
                    "status": "verification_failed",
                    "reason": submission["reason"],
                    "errors": result["errors"],
                    "verification": result.get("verification"),
                    # The controls the filler had no value for. A required one
                    # is what blocked the submit, and it was never forwarded.
                    "skipped": result.get("skipped"),
                },
                page=page, detect=_recovery_detect, log=log,
            )
            if recovered:
                apply_recovery(result, recovered)
                result["tab_left_open"] = False
                try:
                    await page.close()
                    result["tab_closed"] = True
                    print("Tab closed on success.")
                except Exception:
                    pass
                _write_result(output_dir, result)
                _print_summary(result)
                return result

            # Form is loaded and (partially) filled — leave it open so the
            # user can correct the mismatched fields and submit manually.
            state = await _capture_application_state(page)
            form_found = bool(result["filled"]) or int(state.get("controlCount") or 0) > 0
            keep_tab_open = should_keep_tab_open("verification_failed", form_found=form_found)
            result["tab_left_open"] = keep_tab_open
            if keep_tab_open:
                result["tab_left_open_reason"] = "verification_failed"
                print(f"Leaving tab open for manual completion (verification_failed: {submission['reason']})")
            else:
                await session.cleanup()
            _write_result(output_dir, result)
            _print_summary(result)
            return result

        if not submit_enabled():
            # Fill-and-verify only. Ashby had no gate at all before this — and it
            # also auto-RETRIES the submit twice, so a test run could send three.
            print("JOB_AUTOMATOR_SUBMIT=0 — filled but not submitted.")
            result["submission"] = {"status": "not_submitted",
                                    "reason": "JOB_AUTOMATOR_SUBMIT=0"}
            result["tab_left_open"] = False
            if unattended_run():
                await session.cleanup()
            _write_result(output_dir, result)
            _print_summary(result)
            return result

        before_submit_state = await _capture_application_state(page)

        submitted = await _click_submit_with_playwright(page)
        if submitted:
            print("Clicked submit (trusted Playwright)")

        if not submitted:
            # Try CSS selectors with JS when a visible trusted button is unavailable.
            for js_sel in ["button[type='submit']", "button[type=submit]"]:
                try:
                    clicked = await page.evaluate(f"""
                    () => {{
                        const btn = document.querySelector({json.dumps(js_sel)});
                        if (!btn) return false;
                        btn.click();
                        return true;
                    }}
                    """)
                    if clicked:
                        submitted = True
                        print(f"Clicked submit (JS): {js_sel}")
                        break
                except Exception:
                    pass
        if not submitted:
            # Text-based JS fallback — find any button whose text includes "Submit"
            clicked = await page.evaluate("""
            () => {
                for (const btn of document.querySelectorAll('button')) {
                    if ((btn.textContent || '').trim().toLowerCase().includes('submit')) {
                        btn.click();
                        return btn.textContent.trim();
                    }
                }
                return null;
            }
            """)
            if clicked:
                submitted = True
                print(f"Clicked submit (JS text): {clicked!r}")
        if not submitted:
            print("Submit button not found — please click manually.")

        try:
            # Wait for success page or networkidle — Ashby navigates to a thank-you page
            await page.wait_for_url("**/confirmation**", timeout=10000)
        except Exception:
            try:
                await page.wait_for_load_state("networkidle", timeout=10000)
            except Exception:
                await asyncio.sleep(4)
        try:
            await page.screenshot(path=str(output_dir / "submitted.png"), full_page=True)
        except Exception:
            pass

        # Ashby swaps in its status panel in place, sometimes a beat after the
        # click. Settle before calling it not_confirmed and paying for recovery.
        submission = await settle_submission(
            lambda: _detect_submission_state(page, submitted, before_submit_state, network_responses))
        if submission["status"] != "submitted":
            if await _click_submit_with_playwright(page):
                submitted = True
                print("Retrying submit with trusted Playwright click")
                await _wait_after_submit(page)
                try:
                    await page.screenshot(path=str(output_dir / "submitted_retry.png"), full_page=True)
                except Exception:
                    pass
                # The retry paths produce the FINAL verdict, so a one-shot read here
                # undoes the settle above: two not_confirmed results went straight to
                # blind recovery (279s) for an answer that was merely late.
                submission = await settle_submission(
                    lambda: _detect_submission_state(
                        page, submitted, before_submit_state, network_responses))
        if submission["status"] != "submitted":
            retry_count = await _retry_required_error_fields(page, fields, answers)
            if retry_count:
                print(f"Re-filled {retry_count} required-error field(s) and retrying submit")
                if await _click_submit_with_playwright(page):
                    submitted = True
                else:
                    submitted = await _click_submit_with_js_text(page)
                await _wait_after_submit(page)
                try:
                    await page.screenshot(path=str(output_dir / "submitted_required_retry.png"), full_page=True)
                except Exception:
                    pass
                # The retry paths produce the FINAL verdict, so a one-shot read here
                # undoes the settle above: two not_confirmed results went straight to
                # blind recovery (279s) for an answer that was merely late.
                submission = await settle_submission(
                    lambda: _detect_submission_state(
                        page, submitted, before_submit_state, network_responses))
        result["submission"] = submission
        log("submit.state", status=submission["status"], reason=submission.get("reason"))
        if submission["status"] != "submitted":
            result["errors"].append({
                "id": "_submission",
                "error": f"{submission['status']}: {submission['reason']}",
            })

            # AI recovery: agent fixes the live tab and submits; only a
            # detector-confirmed submit flips the status.
            async def _recovery_detect() -> bool:
                detected = await _detect_submission_state(page, True, before_submit_state, network_responses)
                return detected.get("status") == "submitted"

            recovered = await attempt_recovery(
                platform="ashby", apply_url=apply_url, payload=payload,
                result=result, output_dir=output_dir,
                failure={
                    "status": submission["status"],
                    "reason": submission.get("reason", ""),
                    "errors": result["errors"],
                    "verification": result.get("verification"),
                    # The controls the filler had no value for. A required one
                    # is what blocked the submit, and it was never forwarded.
                    "skipped": result.get("skipped"),
                },
                page=page, detect=_recovery_detect, log=log,
            )
            if recovered:
                submission = apply_recovery(result, recovered)
        # Keep the tab open on any failure so the user can finish manually;
        # close only on success or when the form was never found.
        form_found = int(before_submit_state.get("controlCount") or 0) > 0
        keep_tab_open = should_keep_tab_open(submission["status"], form_found=form_found)
        result["tab_left_open"] = keep_tab_open
        if keep_tab_open:
            result["tab_left_open_reason"] = submission["status"]

        # Close tab on confirmed success.
        try:
            if submission["status"] == "submitted":
                await page.close()
                print("Tab closed on success.")
                result["tab_closed"] = True
        except Exception:
            pass

        if keep_tab_open:
            log("tab.policy", keep_open=True, reason=submission["status"])
            # A tab left open is one the user is expected to finish by hand,
            # so it must stop claiming it is still being filled.
            await tab_tag.apply_stage(
                page, tab_tag.stage_for_status(submission["status"]))
        else:
            await session.cleanup()

    _write_result(output_dir, result)
    log("result.written", status=(result.get("submission") or {}).get("status"), elapsed_s=log.elapsed_s())
    _print_summary(result)
    return result


async def _wait_for_resume_analysis(page: Page) -> None:
    """Wait for Ashby's resume analysis spinner to disappear before filling fields."""
    try:
        await page.wait_for_selector("text=Analyzing", timeout=6000)
    except Exception:
        return
    try:
        await page.wait_for_selector("text=Analyzing", state="hidden", timeout=30000)
        await page.wait_for_timeout(800)
    except Exception:
        pass


async def _capture_application_state(page: Page) -> dict:
    """Capture generic Ashby page state before/after submit."""
    try:
        return await page.evaluate(
            """
            () => {
                const visible = (el) => {
                    const style = getComputedStyle(el);
                    const rect = el.getBoundingClientRect();
                    return rect.width > 0 && rect.height > 0
                        && style.visibility !== 'hidden'
                        && style.display !== 'none'
                        && Number(style.opacity || '1') > 0;
                };
                const rgb = (value) => {
                    const m = String(value || '').match(/rgba?\\((\\d+),\\s*(\\d+),\\s*(\\d+)/i);
                    return m ? [Number(m[1]), Number(m[2]), Number(m[3])] : null;
                };
                const colorKind = (value) => {
                    const c = rgb(value);
                    if (!c) return '';
                    const [r, g, b] = c;
                    if (r >= 120 && r > g * 1.25 && r > b * 1.25) return 'red';
                    if (g >= 90 && g > r * 1.15 && g > b * 1.15) return 'green';
                    return '';
                };
                const fieldPaths = Array.from(document.querySelectorAll('[data-field-path]')).filter(visible);
                const controls = Array.from(document.querySelectorAll(
                    'input:not([type="hidden"]), textarea, select, [role="combobox"], [contenteditable="true"]'
                )).filter(visible);
                const submitButtons = Array.from(document.querySelectorAll('button[type="submit"], button')).filter((btn) => {
                    if (!visible(btn)) return false;
                    const text = (btn.textContent || '').trim().toLowerCase();
                    return btn.type === 'submit' || text.includes('submit');
                });
                const panels = Array.from(document.querySelectorAll('[role="alert"], [aria-live], [class*="alert"], [class*="toast"], [class*="notification"], div'))
                    .filter(visible)
                    .map((el) => {
                        const style = getComputedStyle(el);
                        const text = (el.textContent || '').replace(/\\s+/g, ' ').trim();
                        const bg = colorKind(style.backgroundColor);
                        const border = colorKind(style.borderColor);
                        return { textLength: text.length, bg, border };
                    })
                    .filter((p) => p.textLength >= 20);
                return {
                    url: location.href,
                    fieldPathCount: fieldPaths.length,
                    controlCount: controls.length,
                    statusPanelCount: panels.length,
                    submitButtonCount: submitButtons.length,
                    greenStatusCount: panels.filter((p) => p.bg === 'green' || p.border === 'green').length,
                    redStatusCount: panels.filter((p) => p.bg === 'red' || p.border === 'red').length,
                    invalidControlCount: controls.filter((el) => el.getAttribute('aria-invalid') === 'true').length,
                    captchaFrameCount: document.querySelectorAll('iframe[src*="captcha" i], iframe[title*="captcha" i]').length,
                    bodyText: (document.body?.innerText || '').replace(/\\s+/g, ' ').trim().slice(0, 4000),
                };
            }
            """
        )
    except Exception as exc:
        return {"error": str(exc)}


async def _detect_submission_state(page: Page, clicked_submit: bool, before_state: dict | None = None,
                                   network_responses: list[dict] | None = None) -> dict:
    """Classify whether Ashby actually accepted the application after submit."""
    if not clicked_submit:
        return {"status": "submit_button_not_found", "reason": "no submit button was clicked"}

    current_url = page.url
    url_l = current_url.lower()
    if any(kw in url_l for kw in ("thank", "success", "confirmation", "submitted", "complete")):
        return {"status": "submitted", "reason": f"success URL: {current_url}"}

    state = await _capture_application_state(page)
    text_l = " ".join(str(state.get("bodyText", "")).lower().split())

    duplicate_phrases = [
        "already applied to this position",
        "cannot apply for the same role again",
        "applied to this position in the last",
    ]
    if any(phrase in text_l for phrase in duplicate_phrases):
        return {"status": "duplicate_application", "reason": "duplicate application message found"}

    # The posting is gone. There was never an application to make, so this is
    # not a failure to recover from -- greenhouse already classified its own
    # version of this as posting_closed, ashby had nothing and sent it to the
    # AI agent instead. Checked BEFORE the confirmation text so a 404 page
    # cannot be read as a success.
    gone = posting_gone(state.get("bodyText"))
    if gone:
        return {"status": "posting_closed", "reason": f"posting is gone: {gone!r}"}

    # Ashby can confirm in place, leaving enough of the page behind that none of
    # the structural tests below fire. bodyText was already collected here and
    # simply never read for it -- the same omission that cost lever a wasted
    # recovery run. Past-tense only, so "your application will be submitted"
    # cannot match.
    confirmed = confirmation_text(state.get("bodyText"))
    if confirmed:
        return {"status": "submitted", "reason": f"confirmation on page: {confirmed!r}"}

    if state.get("redStatusCount", 0) or state.get("invalidControlCount", 0):
        return {"status": "not_confirmed", "reason": "visible validation/error state remains after submit"}

    before_fields = int((before_state or {}).get("fieldPathCount") or 0)
    after_fields = int(state.get("fieldPathCount") or 0)
    after_controls = int(state.get("controlCount") or 0)
    status_panels = int(state.get("statusPanelCount") or 0)
    after_submit_buttons = int(state.get("submitButtonCount") or 0)
    green_panels = int(state.get("greenStatusCount") or 0)

    if before_fields > 0:
        if after_fields == 0 and after_submit_buttons == 0 and status_panels > 0:
            return {"status": "submitted", "reason": "application form replaced by status panel"}
        if after_fields == 0 and after_controls == 0 and after_submit_buttons == 0:
            return {"status": "submitted", "reason": "application form disappeared after submit"}
        if green_panels and after_fields == 0 and after_submit_buttons == 0:
            return {"status": "submitted", "reason": "green status panel replaced application form"}
        if green_panels and after_submit_buttons == 0:
            return {"status": "submitted", "reason": "green status panel replaced application form"}
        if green_panels and after_fields < before_fields:
            return {"status": "submitted", "reason": "application form shrank to green status state"}
        if state.get("url") != (before_state or {}).get("url") and after_fields == 0:
            return {"status": "submitted", "reason": "page navigated away from application form"}

    if green_panels and not after_submit_buttons:
        return {"status": "submitted", "reason": "green status panel after submit"}

    if state.get("captchaFrameCount", 0):
        return {"status": "not_confirmed", "reason": "captcha iframe still present and form did not transition"}

    # Nothing on the page says it worked. Before calling this not_confirmed --
    # which sends it to a recovery agent instructed to complete and SUBMIT --
    # check whether ashby already told us it accepted the application. Strictly
    # a tiebreaker: it can only turn not_confirmed into submitted.
    accepted = accepted_by_network(network_responses)
    if accepted:
        return {"status": "submitted",
                "reason": f"board accepted: HTTP {accepted.get('status')} {accepted.get('url')}"}

    return {"status": "not_confirmed", "reason": "application form did not transition to submitted state"}


