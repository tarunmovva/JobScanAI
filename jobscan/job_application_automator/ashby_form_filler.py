async def _retry_required_error_fields(page: Page, fields: dict, answers: dict) -> int:
    labels = await _missing_required_labels(page)
    if not labels:
        return 0

    matched = []
    normalized_labels = [_norm_label(label) for label in labels]
    for field_id, answer in answers.items():
        if answer is None or answer == "":
            continue
        field_def = fields.get(field_id, {})
        label = _norm_label(field_def.get("label") or field_id)
        if not any(label and (label in missing or missing in label) for missing in normalized_labels):
            continue
        ftype = field_def.get("type") or _guess_type(field_id, answer)
        selector = field_def.get("selector", "")
        ok, _ = await _fill_field(page, field_id, ftype, answer, selector, field_def)
        if ok:
            matched.append(field_id)
            await page.wait_for_timeout(200)
    return len(matched)


async def _missing_required_labels(page: Page) -> list[str]:
    try:
        return await page.evaluate(
            """
            () => {
                const text = document.body?.innerText || '';
                const labels = [];
                const rx = /Missing entry for required field:\\s*([^\\n]+)/gi;
                let match;
                while ((match = rx.exec(text)) !== null) {
                    const label = (match[1] || '').replace(/\\s+/g, ' ').trim();
                    if (label) labels.push(label);
                }
                return labels;
            }
            """
        )
    except Exception:
        return []


def _norm_label(value: str) -> str:
    return re.sub(r"[^a-z0-9]+", " ", str(value or "").lower()).strip()


# Diagnostics returned alongside ok=True that mean the field is filled but NOT
# the way it was asked for — the combobox fell back to typing, or no combobox was
# found at all. These belong in errors[] so recovery can see them; a plain
# "selected option: ..." confirmation does not.
_DEGRADED_FILL_MARKERS = (
    "no dropdown option selected",
    "no combobox found",
    # Both of these returned ok=True with no error, so recovery launched BLIND
    # against a field it was never told about.
    "no confident option match",
    "value did not commit",
)


def _is_degraded_fill(note: str) -> bool:
    text = str(note or "").lower()
    return any(marker in text for marker in _DEGRADED_FILL_MARKERS)


async def _fill_field(
    page: Page,
    field_id: str,
    ftype: str,
    value,
    selector: str,
    field_def: dict,
) -> tuple[bool, str]:
    try:
        if ftype == "file":
            return await _fill_file(page, field_id, value, selector)

        if ftype == "select":
            return await _fill_select(page, field_id, value, selector)

        if ftype == "radio":
            return await _fill_radio_ashby_scoped(page, field_id, value, selector, field_def)

        if ftype in ("checkbox",):
            return await _fill_checkbox_single(page, field_id, value, selector)

        if ftype == "multi_checkbox":
            return await _fill_multi_checkbox(page, field_id, value, field_def)

        if ftype == "combobox":
            return await _fill_combobox_scoped(page, field_id, value, selector, field_def)

        if ftype == "date":
            return await _fill_date(page, field_id, value, selector)

        # The extractor types a react-datepicker as "text": it has no name and no
        # id, so it falls back to the generic data-field-path selector. _fill_date
        # and _parse_date_value (which literally special-cases "two week") existed
        # four months before this failure and were simply never dispatched to.
        # Ask the DOM instead of trusting the declared type.
        if ftype in ("text", "textarea") and await _looks_like_datepicker(page, field_id, selector):
            ok, err = await _fill_date(page, field_id, value, selector)
            if ok:
                return True, err or "routed to date picker"
            return False, f"date picker: {err}"

        if ftype in ("text", "email", "url", "tel", "textarea", "number"):
            return await _fill_text(page, field_id, ftype, value, selector)

        return False, f"unknown type {ftype}"

    except Exception as exc:
        return False, str(exc)


async def _looks_like_datepicker(page: Page, field_id: str, selector: str) -> bool:
    """True when the control is a react-datepicker rather than a free text box.

    Detected from the DOM, not from the extracted type, because the extractor has
    no way to tell: the input carries neither name nor id, only a wrapper class.
    """
    for sel in _candidate_selectors("input", field_id, selector):
        try:
            el = page.locator(sel).first
            if not await el.count():
                continue
            return bool(await el.evaluate(
                """(node) => {
                    if (node.closest('.react-datepicker-wrapper, .react-datepicker__input-container')) return true;
                    const cls = String(node.className || '');
                    if (/input-date|datepicker/i.test(cls)) return true;
                    const ph = String(node.getAttribute('placeholder') || '');
                    return /pick date|select date|mm[^a-z]dd|dd[^a-z]mm|yyyy/i.test(ph);
                }"""))
        except Exception:
            continue
    return False


async def _fill_text(page: Page, field_id: str, ftype: str, value: str, selector: str) -> tuple[bool, str]:
    tag = "textarea" if ftype == "textarea" else "input"
    str_value = str(value)
    for sel in _candidate_selectors(tag, field_id, selector):
        try:
            el = page.locator(sel).first
            if await el.count():
                try:
                    await el.scroll_into_view_if_needed(timeout=2000)
                except Exception:
                    pass
                await el.click()
                await el.press("Control+a")
                await page.keyboard.type(str_value, delay=8)
                # Read back. Typing into a control that rejects the value —
                # <input type="number"> given "120000-140000", a react-datepicker
                # given "Two weeks notice" — leaves it EMPTY, and returning True
                # here made that invisible until pre-submit verification.
                try:
                    actual = await el.input_value(timeout=1500)
                except Exception:
                    actual = None
                if actual is not None and actual.strip() == "" and str_value.strip():
                    return False, (
                        f"control rejected the value (reads back empty): {str_value!r}"
                        + (" — the control is numeric, so a range or units cannot be typed"
                           if ftype == "number" else "")
                    )
                return True, ""
        except Exception:
            try:
                proto = "HTMLTextAreaElement" if ftype == "textarea" else "HTMLInputElement"
                ok = await page.evaluate(f"""
                (sel) => {{
                    const el = document.querySelector(sel);
                    if (!el) return false;
                    const setter = Object.getOwnPropertyDescriptor(window.{proto}.prototype, 'value')?.set
                        || Object.getOwnPropertyDescriptor(window.HTMLInputElement.prototype, 'value')?.set
                        || Object.getOwnPropertyDescriptor(window.HTMLTextAreaElement.prototype, 'value')?.set;
                    if (setter) setter.call(el, {json.dumps(str_value)});
                    else el.value = {json.dumps(str_value)};
                    el.dispatchEvent(new Event('input', {{ bubbles: true }}));
                    el.dispatchEvent(new Event('change', {{ bubbles: true }}));
                    return true;
                }}
                """, sel)
                if ok:
                    return True, "filled via JS"
            except Exception:
                pass
            continue
    return False, f"not found: {selector!r} or {tag}[name={field_id!r}]"


async def _fill_date(page: Page, field_id: str, value, selector: str) -> tuple[bool, str]:
    """Fill Ashby's React date picker using parseable typed date formats."""
    candidates = _date_candidates(value)
    if not candidates:
        return False, f"no date candidates for {value!r}"

    for sel in _candidate_selectors("input", field_id, selector):
        try:
            el = page.locator(sel).first
            if not await el.count():
                continue
            try:
                await el.scroll_into_view_if_needed(timeout=2000)
            except Exception:
                pass
            for candidate in candidates:
                try:
                    await el.click()
                    await el.press("Control+a")
                    await el.fill(candidate)
                    await el.press("Tab")
                    await page.wait_for_timeout(250)
                    actual = await _read_input_value(page, field_id, sel)
                    if actual:
                        return True, "" if _date_values_match(value, actual) else f"filled date as {actual}"
                except Exception:
                    continue

                try:
                    ok = await page.evaluate(
                        """
                        ({ selector, value }) => {
                            const el = document.querySelector(selector);
                            if (!el) return false;
                            const setter = Object.getOwnPropertyDescriptor(window.HTMLInputElement.prototype, 'value')?.set;
                            if (setter) setter.call(el, value);
                            else el.value = value;
                            el.dispatchEvent(new Event('input', { bubbles: true }));
                            el.dispatchEvent(new Event('change', { bubbles: true }));
                            el.dispatchEvent(new Event('blur', { bubbles: true }));
                            return true;
                        }
                        """,
                        {"selector": sel, "value": candidate},
                    )
                    if ok:
                        await page.wait_for_timeout(250)
                        actual = await _read_input_value(page, field_id, sel)
                        if actual:
                            return True, "filled date via JS"
                except Exception:
                    pass
        except Exception:
            continue

    return False, f"date input not found or rejected value for {field_id!r}"


async def _fill_file(page: Page, field_id: str, value: str, selector: str) -> tuple[bool, str]:
    path = Path(value)
    if not path.exists():
        return False, f"file not found: {value}"
    for sel in [
        selector,
        f'input[name="{field_id}"]',
        f'input[id="{field_id}"]',
        'input[type="file"][name="_systemfield_resume"]',
    ]:
        if not sel:
            continue
        el = page.locator(sel).first
        if await el.count():
            await el.set_input_files(str(path))
            return True, ""
    return False, f"file input not found for {field_id!r}"


async def _fill_select(page: Page, field_id: str, value: str, selector: str) -> tuple[bool, str]:
    for sel in [selector, f'select[name="{field_id}"]']:
        if not sel:
            continue
        el = page.locator(sel).first
        if await el.count():
            try:
                await el.select_option(label=value)
                return True, ""
            except Exception:
                await el.select_option(value=value)
                return True, ""
    return False, f"select not found: {field_id!r}"


async def _click_boolean_button_scoped(page: Page, field_id: str, want_bool: bool) -> tuple[bool, str] | None:
    """Click Ashby's visible Yes/No button with trusted browser events."""
    container = page.locator(f'[data-field-path="{field_id}"]').first
    if not await container.count():
        return None

    target = "Yes" if want_bool else "No"
    buttons = container.get_by_role("button", name=re.compile(f"^{target}$", re.I))
    if not await buttons.count():
        return None

    opposite = "No" if want_bool else "Yes"
    opposite_buttons = container.get_by_role("button", name=re.compile(f"^{opposite}$", re.I))
    if await opposite_buttons.count():
        opposite_btn = opposite_buttons.first
        try:
            await opposite_btn.scroll_into_view_if_needed(timeout=3000)
        except Exception:
            pass
        await opposite_btn.click(timeout=5000)
        await page.wait_for_timeout(120)

    btn = buttons.first
    try:
        await btn.scroll_into_view_if_needed(timeout=3000)
    except Exception:
        pass
    await btn.click(timeout=5000)
    await page.wait_for_timeout(150)
    return True, ""


async def _fill_radio_ashby(
    page: Page, field_id: str, value: str, selector: str, field_def: dict
) -> tuple[bool, str]:
    """Click an Ashby radio option by matching label text.

    Ashby radios: each option is input[type=radio] with a label[for=id] showing option text.
    The group_name in field_def.group_name is the shared name attribute across options.
    """
    options = field_def.get("options", [])
    target_lower = str(value).lower()

    # Try clicking by option selector from field_def
    for opt in options:
        if not isinstance(opt, dict):
            continue
        opt_label = (opt.get("label") or "").strip()
        opt_sel = opt.get("selector", "")
        if opt_label.lower() == target_lower and opt_sel:
            el = page.locator(opt_sel).first
            if await el.count():
                await _set_radio_checked(page, el)
                return True, ""

    # Fallback: find by label text globally with trusted Playwright clicks.
    radios = page.locator('input[type="radio"]')
    count = await radios.count()
    for idx in range(count):
        radio = radios.nth(idx)
        label_text = await _input_label_text(page, radio)
        if _norm_value(label_text) == _norm_value(value):
            if await _set_radio_checked(page, radio):
                return True, ""

    # Last resort: check first radio in the group
    group_name = field_def.get("group_name") or field_id
    el = page.locator(f'input[type=radio][name="{group_name}"]').first
    if await el.count():
        await _set_radio_checked(page, el)
        return True, f"no label match for {value!r} — checked first option"

    return False, f"radio not found: {field_id!r}"


def _css_attr(value: str) -> str:
    return str(value).replace("\\", "\\\\").replace('"', '\\"')


async def _input_label_text(page: Page, input_locator) -> str:
    try:
        return await input_locator.evaluate(
            """
            (el) => {
                let label = null;
                if (el.id) {
                    label = document.querySelector(`label[for="${CSS.escape(el.id)}"]`);
                }
                label = label || el.closest('label') || el.parentElement?.querySelector('label');
                return (label?.textContent || el.value || el.name || '').replace(/\\s+/g, ' ').trim();
            }
            """
        )
    except Exception:
        return ""


async def _click_input_label_or_control(page: Page, input_locator) -> bool:
    """Use trusted Playwright clicks so Ashby's React state matches the visible state."""
    try:
        await input_locator.evaluate("el => el.scrollIntoView({ block: 'center', inline: 'nearest' })")
    except Exception:
        pass

    try:
        input_id = await input_locator.get_attribute("id")
    except Exception:
        input_id = None

    if input_id:
        try:
            label = page.locator(f'label[for="{_css_attr(input_id)}"]').first
            if await label.count():
                await label.evaluate("el => el.scrollIntoView({ block: 'center', inline: 'nearest' })")
                await label.click(timeout=5000)
                return True
        except Exception:
            pass

    try:
        wrapping_label = input_locator.locator("xpath=ancestor::label[1]").first
        if await wrapping_label.count():
            await wrapping_label.evaluate("el => el.scrollIntoView({ block: 'center', inline: 'nearest' })")
            await wrapping_label.click(timeout=5000)
            return True
    except Exception:
        pass

    try:
        await input_locator.click(force=True, timeout=5000)
        return True
    except Exception:
        return False


async def _click_containing_option(page: Page, input_locator) -> bool:
    """Click the visible option row that owns a radio/checkbox input."""
    token = f"codex-click-{datetime.now().timestamp()}-{id(input_locator)}".replace(".", "-")
    selector = f'[data-codex-click-target="{token}"]'
    try:
        found = await input_locator.evaluate(
            """
            (el, token) => {
                const fieldset = el.closest('fieldset');
                let target = el.closest('label,[role="radio"],[role="option"],[role="menuitemradio"]');
                if (!target && fieldset) {
                    target = Array.from(fieldset.children).find((child) => child.contains(el));
                }
                if (!target && el.id) {
                    target = document.querySelector(`label[for="${CSS.escape(el.id)}"]`);
                }
                target = target || el;
                target.setAttribute('data-codex-click-target', token);
                return true;
            }
            """,
            token,
        )
        if not found:
            return False
        target = page.locator(selector).first
        if not await target.count():
            return False
        await target.evaluate("el => el.scrollIntoView({ block: 'center', inline: 'nearest' })")
        await target.click(timeout=5000)
        return True
    except Exception:
        return False
    finally:
        try:
            await page.locator(selector).evaluate_all(
                "els => els.forEach((el) => el.removeAttribute('data-codex-click-target'))"
            )
        except Exception:
            pass


_LABELED_CHECKBOX_RE = re.compile(
    r"^(?P<prefix>[0-9a-fA-F-]{36})_(?P<path>[0-9a-fA-F-]{36})-labeled-checkbox-[0-9]+$")


def _durable_field_path(field_id: str) -> str:
    """Pull the durable field path out of a generated checkbox DOM id.

    Ashby names these "<formEntryPrefix>_<fieldPath>-labeled-checkbox-N". Only the
    middle segment matches the container's data-field-path, and only that segment
    survives a remount.
    """
    match = _LABELED_CHECKBOX_RE.match(str(field_id or ""))
    return match.group("path") if match else ""


async def _check_checkbox_by_label(page: Page, field_id: str, target_label: str) -> bool:
    container = page.locator(f'[data-field-path="{_css_attr(field_id)}"]').first
    if not await container.count():
        return False

    target_norm = _norm_value(target_label)
    boxes = container.locator('input[type="checkbox"]')
    count = await boxes.count()
    for idx in range(count):
        box = boxes.nth(idx)
        label_text = await _input_label_text(page, box)
        if _norm_value(label_text) != target_norm:
            continue
        if not await box.is_checked():
            if not await _set_checkbox_checked(page, box):
                return False
            await page.wait_for_timeout(100)
        else:
            await _dispatch_checkbox_events(box)
        return await box.is_checked()
    return False


async def _dispatch_checkbox_events(input_locator) -> None:
    try:
        await input_locator.dispatch_event("input")
        await input_locator.dispatch_event("change")
    except Exception:
        pass


async def _set_radio_checked(page: Page, input_locator) -> bool:
    """Set a radio option with trusted clicks, then refresh React state."""
    try:
        await input_locator.evaluate("el => el.scrollIntoView({ block: 'center', inline: 'nearest' })")
    except Exception:
        pass

    try:
        if await _click_containing_option(page, input_locator):
            await page.wait_for_timeout(120)
        if not await input_locator.is_checked() and not await _click_input_label_or_control(page, input_locator):
            await input_locator.check(force=True, timeout=5000)
        await input_locator.dispatch_event("input")
        await input_locator.dispatch_event("change")
        if await input_locator.is_checked():
            return True
    except Exception:
        pass

    try:
        await input_locator.check(force=True, timeout=5000)
        await input_locator.dispatch_event("input")
        await input_locator.dispatch_event("change")
        return await input_locator.is_checked()
    except Exception:
        return False


async def _set_checkbox_checked(page: Page, input_locator) -> bool:
    """Set a checkbox with trusted Playwright events, then refresh React state."""
    try:
        await input_locator.evaluate("el => el.scrollIntoView({ block: 'center', inline: 'nearest' })")
    except Exception:
        pass

    try:
        if not await input_locator.is_checked():
            await input_locator.check(force=True, timeout=5000)
        await _dispatch_checkbox_events(input_locator)
        if await input_locator.is_checked():
            return True
    except Exception:
        pass

    if await _click_input_label_or_control(page, input_locator):
        await _dispatch_checkbox_events(input_locator)
        try:
            return await input_locator.is_checked()
        except Exception:
            return True

    return False


async def _fill_checkbox_single(page: Page, field_id: str, value, selector: str) -> tuple[bool, str]:
    # Ashby has two boolean field patterns:
    # 1) Yes/No BUTTON pair: hidden checkbox + "Yes"/"No" BUTTON[type=submit] as DIRECT siblings
    # 2) Single toggle checkbox: input[type=checkbox] controlled via its label click
    # Walk up max 3 levels (immediate parent and grandparent) looking for Yes/No buttons —
    # do NOT walk higher or you'll find Yes/No from other fields and click the wrong ones.
    # bool("No") is True. Answering "No" used to CHECK the box.
    want_bool = truthy(value)
    scoped_button_result = await _click_boolean_button_scoped(page, field_id, want_bool)
    if scoped_button_result is not None:
        return scoped_button_result

    for sel in _candidate_selectors("input", field_id, selector):
        try:
            el = page.locator(sel).first
            if not await el.count():
                continue
            input_type = (await el.get_attribute("type") or "").lower()
            if input_type != "checkbox":
                continue
            if await el.is_checked() != want_bool:
                if not await _click_input_label_or_control(page, el):
                    await el.click(force=True, timeout=5000)
                await _dispatch_checkbox_events(el)
                await page.wait_for_timeout(150)
            else:
                await _dispatch_checkbox_events(el)
            if await el.is_checked() == want_bool:
                return True, ""
        except Exception:
            continue

    result = await page.evaluate(f"""
    () => {{
        const want = {json.dumps(want_bool)};
        const targetText = want ? 'yes' : 'no';
        const sels = [{json.dumps(selector)}, 'input[name="{field_id}"]', '[id="{field_id}"]'];
        for (const s of sels) {{
            if (!s) continue;
            let el;
            try {{ el = document.querySelector(s); }} catch(e) {{ continue; }}
            if (!el) continue;

            // Check up to 3 ancestor levels for Yes/No button pair (they are close siblings)
            let container = el.parentElement;
            for (let i = 0; i < 3 && container; i++) {{
                // Use children-only, not querySelectorAll, to avoid picking up distant buttons
                const directBtns = Array.from(container.children).filter(c => c.tagName === 'BUTTON');
                const yesNoBtns = directBtns.filter(b => {{
                    const t = (b.textContent || '').trim().toLowerCase();
                    return t === 'yes' || t === 'no';
                }});
                if (yesNoBtns.length >= 2) {{
                    for (const btn of yesNoBtns) {{
                        if ((btn.textContent || '').trim().toLowerCase() === targetText) {{
                            btn.click();
                            return true;
                        }}
                    }}
                    yesNoBtns[want ? 0 : 1].click();
                    return true;
                }}
                container = container.parentElement;
            }}

            // No nearby Yes/No buttons — single toggle checkbox
            if (el.type === 'checkbox') {{
                if (el.checked !== want) {{
                    // Prefer label click (triggers React synthetic event)
                    const lbl = el.id ? document.querySelector('label[for="' + el.id + '"]') : null;
                    if (lbl) {{ lbl.click(); }}
                    else {{
                        // Dispatch React-compatible change event
                        const nativeInput = Object.getOwnPropertyDescriptor(window.HTMLInputElement.prototype, 'checked');
                        if (nativeInput && nativeInput.set) nativeInput.set.call(el, want);
                        el.dispatchEvent(new Event('change', {{bubbles: true}}));
                        el.dispatchEvent(new Event('input', {{bubbles: true}}));
                        el.click();
                    }}
                }}
                return true;
            }}
        }}
        return false;
    }}
    """)
    if result:
        return True, ""
    # Last resort: the composite DOM id carries the durable field path inside it.
    # A checkbox with name="" gets identified by its generated id
    # "<formEntryPrefix>_<fieldPath>-labeled-checkbox-N", which React regenerates
    # on remount — so every id/name-derived selector above is dead after a reload,
    # while the container's data-field-path survives. The radio and multi-checkbox
    # paths already scope by data-field-path; this one had no such fallback, which
    # is the entire difference between 17 controls filling and 1 not.
    field_path = _durable_field_path(field_id)
    if field_path and field_path != field_id:
        container = page.locator(f'[data-field-path="{_css_attr(field_path)}"]').first
        try:
            if await container.count():
                box = container.locator('input[type="checkbox"]').first
                if await box.count():
                    try:
                        await box.scroll_into_view_if_needed(timeout=1500)
                    except Exception:
                        pass
                    if bool(await box.is_checked()) != want_bool:
                        try:
                            await box.click(timeout=2500)
                        except Exception:
                            await box.evaluate("(el) => el.click()")
                    if bool(await box.is_checked()) == want_bool:
                        return True, f"checkbox via data-field-path={field_path}"
        except Exception:
            pass
    return False, f"checkbox not found: {field_id!r}"


async def _fill_multi_checkbox(page: Page, field_id: str, value, field_def: dict) -> tuple[bool, str]:
    """Check Ashby multi-select checkboxes by matching label text."""
    if not isinstance(value, list):
        value = [value]

    options = field_def.get("options", [])
    target_set = {str(v).lower() for v in value}
    checked = []
    missing = list(target_set)

    for opt in options:
        opt_label = (opt.get("label") if isinstance(opt, dict) else str(opt) or "").lower()
        if opt_label in target_set:
            opt_sel = opt.get("selector", "") if isinstance(opt, dict) else ""
            el = page.locator(opt_sel).first if opt_sel else None
            if el and await el.count():
                try:
                    if not await el.is_checked():
                        await _set_checkbox_checked(page, el)
                    else:
                        await _dispatch_checkbox_events(el)
                    await page.wait_for_timeout(100)
                    if await el.is_checked():
                        checked.append(opt_label)
                        missing = [m for m in missing if m != opt_label]
                except Exception:
                    pass

    # Fallback: click by label text
    if missing:
        for v in list(missing):
            found = await _check_checkbox_by_label(page, field_id, v)
            if found:
                checked.append(v)
                missing.remove(v)

    if missing:
        return len(checked) > 0, f"not found: {missing}"
    return True, ""


async def _fill_combobox(
    page: Page, field_id: str, value: str, selector: str, field_def: dict
) -> tuple[bool, str]:
    """Fill an Ashby combobox (location picker) by typing and selecting first suggestion."""
    # Click the combobox to open it
    cb_sel = selector or f'[data-field-path="{field_id}"] [role=combobox]'
    cb = page.locator(cb_sel).first
    if not await cb.count():
        cb = page.locator('[role=combobox]').first

    if not await cb.count():
        # Try filling the underlying input directly
        input_sel = field_def.get("input_selector") or f'input[name="{field_id}"]'
        el = page.locator(input_sel).first
        if await el.count():
            await el.fill(str(value))
            return True, "filled input (no combobox found)"
        return False, f"combobox not found: {field_id!r}"

    await cb.click()
    await page.wait_for_timeout(300)

    # Type value into the combobox input
    input_sel = field_def.get("input_selector")
    if input_sel:
        inp = page.locator(input_sel).first
    else:
        inp = page.locator('[role=combobox] input, [role=combobox]').first

    if await inp.count():
        await inp.fill(str(value))
        await page.wait_for_timeout(600)

        # Click first suggestion
        for opt_sel in [
            '[role=option]:first-child',
            '[role=listbox] [role=option]:first-child',
            '[role=listbox] li:first-child',
        ]:
            opt = page.locator(opt_sel).first
            if await opt.count():
                await opt.click()
                return True, ""

        # Press Enter/Tab to accept typed value
        await inp.press("Enter")
        return True, "typed value, no dropdown option selected"

    return False, f"combobox input not found: {field_id!r}"


async def _fill_radio_ashby_scoped(
    page: Page, field_id: str, value: str, selector: str, field_def: dict
) -> tuple[bool, str]:
    """Click a radio option only inside this field's Ashby container."""
    container = page.locator(f'[data-field-path="{_css_attr(field_id)}"]').first
    if not await container.count():
        return False, "field container not found"

    target_norm = _norm_value(value)
    radios = container.locator('input[type="radio"]')
    count = await radios.count()
    for idx in range(count):
        radio = radios.nth(idx)
        label_text = await _input_label_text(page, radio)
        if _norm_value(label_text) != target_norm:
            continue

        try:
            if await _click_containing_option(page, radio):
                await page.wait_for_timeout(120)
            if not await radio.is_checked() and not await _click_input_label_or_control(page, radio):
                await radio.check(force=True, timeout=5000)
            await page.wait_for_timeout(150)
        except Exception:
            try:
                await radio.check(force=True, timeout=5000)
                await page.wait_for_timeout(150)
            except Exception as exc:
                return False, str(exc)

        actual = await _read_radio_value(page, field_id)
        if _verification_match("radio", value, actual):
            return True, ""
        return False, f"radio did not stay selected: expected {value!r}, got {actual!r}"

    return False, f"option not found for {value!r}"


async def _fill_combobox_scoped(
    page: Page, field_id: str, value: str, selector: str, field_def: dict
) -> tuple[bool, str]:
    """Fill the combobox for this field only, then choose a matching option."""
    container = page.locator(f'[data-field-path="{field_id}"]').first
    cb_sel = selector or f'[data-field-path="{field_id}"] [role=combobox]'
    cb = page.locator(cb_sel).first
    if not await cb.count() and await container.count():
        cb = container.locator('[role=combobox]').first

    if not await cb.count():
        input_sel = field_def.get("input_selector") or f'input[name="{field_id}"]'
        el = page.locator(input_sel).first
        if await el.count():
            await el.fill(str(value))
            return True, "filled input (no combobox found)"
        return False, f"combobox not found: {field_id!r}"

    await cb.click()
    await page.wait_for_timeout(300)

    input_sel = field_def.get("input_selector")
    if input_sel:
        inp = page.locator(input_sel).first
    elif await container.count():
        inp = container.locator('input, [role=combobox]').first
    else:
        inp = cb

    if not await inp.count():
        return False, f"combobox input not found: {field_id!r}"

    try:
        await inp.fill(str(value))
    except Exception:
        await page.keyboard.press("Control+A")
        await page.keyboard.type(str(value))

    # Wait for geocoding API suggestions to appear (up to 2.5s).
    # 700ms was too short — the location combobox fetches from an external API.
    try:
        await page.wait_for_selector(
            '[role="option"], [role="listbox"] [role="option"], [role="listbox"] li',
            timeout=2500,
        )
    except Exception:
        pass  # no suggestions appeared; fall through to Enter fallback

    clicked = await page.evaluate(
        """
        ({ expected }) => {
            const norm = (s) => (s || '').replace(/\\s+/g, ' ').trim().toLowerCase();
            const terms = norm(expected)
                .split(/[^a-z0-9+-]+/)
                .filter(t => t && !['the','and','or','in','of','united','states'].includes(t));
            const visible = (el) => {
                const r = el.getBoundingClientRect();
                const style = getComputedStyle(el);
                return r.width > 0 && r.height > 0 && style.visibility !== 'hidden' && style.display !== 'none';
            };
            const candidates = Array.from(document.querySelectorAll('[role="option"], [role="listbox"] li, [data-highlighted], [cmdk-item]'))
                .filter(visible)
                .map((el) => ({ el, text: (el.textContent || '').trim() }))
                .filter(o => o.text);
            if (!candidates.length) return { clicked: false, reason: 'no options' };

            const expectedNorm = norm(expected);
            let best = null;
            for (const item of candidates) {
                const itemNorm = norm(item.text);
                const itemTerms = itemNorm.split(' ').filter(Boolean);
                let score = 0;
                if (itemNorm === expectedNorm) score += 100;
                if (itemNorm.includes(expectedNorm) || expectedNorm.includes(itemNorm)) score += 50;
                for (const term of terms) {
                    if (itemNorm.includes(term)) score += 10;
                }
                const extras = itemTerms.filter((t) => !terms.includes(t)).length;
                const allTermsPresent = terms.length > 0
                    && terms.every((t) => itemNorm.includes(t));
                const cand = { ...item, score, extras, allTermsPresent };
                // Rank by score, then FEWEST extra tokens — greenhouse's rule,
                // which is what stops a bare city answer picking "Birmingham,
                // West Midlands, United Kingdom" over "Birmingham,
                // Alabama, United States".
                if (!best || score > best.score
                    || (score === best.score && extras < best.extras)) best = cand;
            }
            // score > 0 accepted a SINGLE shared word: "Birmingham, Alabama,
            // United States" scored 10 against "United Kingdom" and clicked it.
            // Require an exact match, containment either way, or every expected
            // token present. Refusing to guess leaves the field unfilled and
            // reported, which recovery can act on — clicking the wrong option
            // silently submits a wrong answer.
            const acceptable = best && (best.score >= 50 || best.allTermsPresent);
            if (!acceptable) {
                return { clicked: false, reason: 'no confident option match',
                         best: best ? best.text : null,
                         options: candidates.map(c => c.text).slice(0, 5) };
            }
            best.el.click();
            return { clicked: true, text: best.text, score: best.score };
        }
        """,
        {"expected": str(value)},
    )
    async def _committed() -> str:
        """What verification will read back, using verification's own reader."""
        await page.wait_for_timeout(300)
        got = str(await _read_combobox_value(page, field_id) or "").strip()
        return "" if got == "<uncommitted>" else got

    if clicked and clicked.get("clicked"):
        # Clicking an option is NOT the same as the value landing. React can
        # drop it, and this used to return ok=True without ever looking --
        # which is how three combobox fields reported "filled" while
        # verification read back "". Confirm through the SAME reader
        # verification uses, so the filler cannot disagree with the verifier.
        got = await _committed()
        if got:
            return True, f"selected option: {clicked.get('text', '')}"
        await inp.press("Enter")
        got = await _committed()
        if got:
            return True, f"selected option via Enter: {got}"
        return True, f"value did not commit (clicked {clicked.get('text', '')!r})"

    await inp.press("Enter")
    got = await _committed()
    if got:
        return True, f"committed via Enter: {got}"
    if clicked and clicked.get("reason"):
        return True, f"{clicked['reason']} (value did not commit)"
    return True, "typed value, no dropdown option selected"


def _candidate_selectors(tag: str, field_id: str, provided: str) -> list[str]:
    sels = []
    if provided:
        sels.append(provided)
    sels.append(f'{tag}[name="{field_id}"]')
    sels.append(f'[id="{field_id}"]')
    sels.append(f'[data-field-path="{field_id}"] {tag}')
    if tag != "input":
        sels.append(f'[data-field-path="{field_id}"] input')
    if tag != "textarea":
        sels.append(f'[data-field-path="{field_id}"] textarea')
    return sels


async def _read_input_value(page: Page, field_id: str, selector: str = "") -> str:
    return await page.evaluate(
        """
        ({ fieldId, selector }) => {
            let el = null;
            if (selector) {
                try { el = document.querySelector(selector); } catch (e) {}
            }
            const container = document.querySelector(`[data-field-path="${CSS.escape(fieldId)}"]`);
            el = el || container?.querySelector('input:not([type="hidden"]), textarea') || null;
            return (el?.value || '').trim();
        }
        """,
        {"fieldId": field_id, "selector": selector},
    )


def _date_candidates(value) -> list[str]:
    parsed = _parse_date_value(value)
    raw = str(value or "").strip()
    candidates: list[str] = []
    if parsed:
        candidates.extend([
            parsed.strftime("%m/%d/%Y"),
            parsed.strftime("%Y-%m-%d"),
            parsed.strftime("%d/%m/%Y"),
            parsed.strftime("%B %-d, %Y") if sys.platform != "win32" else parsed.strftime("%B %#d, %Y"),
        ])
    if raw:
        candidates.append(raw)

    unique: list[str] = []
    seen: set[str] = set()
    for candidate in candidates:
        key = candidate.lower()
        if candidate and key not in seen:
            seen.add(key)
            unique.append(candidate)
    return unique


def _parse_date_value(value) -> datetime | None:
    raw = str(value or "").strip()
    if not raw:
        return None
    lowered = raw.lower()
    if "two week" in lowered or "2 week" in lowered:
        return datetime.now() + timedelta(days=14)
    if lowered in {"immediately", "immediate", "as soon as possible", "asap"}:
        return datetime.now()

    for fmt in ("%Y-%m-%d", "%m/%d/%Y", "%d/%m/%Y", "%B %d, %Y", "%b %d, %Y"):
        try:
            return datetime.strptime(raw, fmt)
        except ValueError:
            continue
    return None


def _date_values_match(expected, actual) -> bool:
    expected_dt = _parse_date_value(expected)
    actual_dt = _parse_date_value(actual)
    if expected_dt and actual_dt:
        return expected_dt.date() == actual_dt.date()
    return _norm_value(expected) == _norm_value(actual)


def _load_extracted_fields(payload_path: Path) -> dict:
    """Load extractor field metadata from common payload/artifact layouts."""
    candidates = [
        payload_path.parent / "extracted_fields.json",
        payload_path.parent / "extract" / "extracted_fields.json",
    ]
    for extracted_path in candidates:
        if not extracted_path.exists():
            continue
        try:
            extracted = json.loads(extracted_path.read_text(encoding="utf-8"))
        except Exception:
            continue
        return {f["id"]: f for f in extracted.get("fields", []) if "id" in f}
    return {}


def _guess_type(field_id: str, value) -> str:
    if isinstance(value, list):
        return "multi_checkbox"
    if isinstance(value, bool):
        return "checkbox"
    if "_systemfield_resume" in field_id or "file" in field_id:
        return "file"
    if "_systemfield_email" in field_id or "email" in field_id:
        return "email"
    if "_systemfield_phone" in field_id or "phone" in field_id:
        return "tel"
    if "location" in field_id.lower():
        return "combobox"
    return "text"


async def _verify_filled(page: Page, fields: dict, answers: dict) -> dict:
    """Check DOM values match answers while the form is still filled."""
    checks = []
    for field_id, answer in answers.items():
        if answer is None or answer == "":
            continue
        field_def = fields.get(field_id, {})
        ftype = field_def.get("type") or _guess_type(field_id, answer)
        sel = field_def.get("selector", f'input[name="{field_id}"]')

        if ftype == "file":
            continue

        if ftype == "radio":
            actual = await _read_radio_value(page, field_id)
        elif ftype == "combobox":
            actual = await _read_combobox_value(page, field_id)
        elif ftype == "multi_checkbox":
            actual = await _read_multi_checkbox_value(page, field_id)
        elif ftype == "checkbox":
            actual = await _read_checkbox_value(page, field_id, sel)
        elif ftype == "select":
            actual = await page.evaluate(
                """
                ({ selector }) => {
                    const el = document.querySelector(selector);
                    if (!el) return null;
                    return el.selectedOptions?.[0]?.textContent?.trim() || el.value || '';
                }
                """,
                {"selector": sel},
            )
        else:
            actual = await page.evaluate(
                """
                ({ selector, fieldId }) => {
                    const el = document.querySelector(selector);
                    const container = document.querySelector(`[data-field-path="${CSS.escape(fieldId)}"]`);
                    const fallback = container?.querySelector('input, textarea');
                    const target = el || fallback;
                    if (!target) return null;
                    return (target.value || target.textContent || '').trim();
                }
                """,
                {"selector": sel, "fieldId": field_id},
            )

        expected = answer
        match = _verification_match(ftype, expected, actual)
        checks.append({
            "id": field_id,
            "expected": _short_value(expected),
            "actual": _short_value(actual),
            "pass": match,
        })

    passed = sum(1 for c in checks if c["pass"])
    return {"checks": checks, "summary": f"{passed}/{len(checks)} value checks passed"}


async def _read_radio_value(page: Page, field_id: str) -> str | None:
    return await page.evaluate(
        """
        ({ fieldId }) => {
            const container = document.querySelector(`[data-field-path="${CSS.escape(fieldId)}"]`);
            if (!container) return null;
            const checked = container.querySelector('input[type="radio"]:checked');
            if (!checked) return '';
            const label = checked.id ? document.querySelector(`label[for="${CSS.escape(checked.id)}"]`) : null;
            return (label?.textContent || checked.value || '').replace(/\\s+/g, ' ').trim();
        }
        """,
        {"fieldId": field_id},
    )


async def _read_combobox_value(page: Page, field_id: str) -> str | None:
    return await page.evaluate(
        """
        ({ fieldId }) => {
            const container = document.querySelector(`[data-field-path="${CSS.escape(fieldId)}"]`);
            if (!container) return null;
            const input = container.querySelector('input');
            // Ashby has no separate committed-value node the way greenhouse does
            // (no single-value element, no chips, no aria-selected) — the chosen
            // option really is written back into input.value. The signal that
            // separates a COMMITTED value from a half-typed one is the menu:
            //   typed "Birmingham"                    -> aria-expanded="true"
            //   picked "Birmingham, Alabama, US"      -> aria-expanded="false"
            // Verification runs long after the fill, so a still-open menu means
            // nothing was ever selected and the box holds a fragment.
            if (input && String(input.getAttribute('aria-expanded')) === 'true') {
                return '<uncommitted>';
            }
            if (input && input.value) return input.value.trim();
            const combo = container.querySelector('[role="combobox"]');
            if (!combo) return '';
            return (combo.value || combo.textContent || '').replace(/\\s+/g, ' ').trim();
        }
        """,
        {"fieldId": field_id},
    )


async def _read_multi_checkbox_value(page: Page, field_id: str) -> list[str] | None:
    return await page.evaluate(
        """
        ({ fieldId }) => {
            const container = document.querySelector(`[data-field-path="${CSS.escape(fieldId)}"]`);
            if (!container) return null;
            return Array.from(container.querySelectorAll('input[type="checkbox"]:checked')).map((cb) => {
                const label = cb.id ? document.querySelector(`label[for="${CSS.escape(cb.id)}"]`) : null;
                return (label?.textContent || cb.name || '').replace(/\\s+/g, ' ').trim();
            }).filter(Boolean);
        }
        """,
        {"fieldId": field_id},
    )


async def _read_checkbox_value(page: Page, field_id: str, selector: str = "") -> bool | None:
    # fieldPath is tried before fieldId: a checkbox with name="" is identified by
    # a generated id whose prefix React regenerates on remount, so by read-back
    # time both the id and the id-derived selector can be dead while the
    # container's data-field-path is unchanged. The FILL path already falls back
    # this way; without the same fallback here a correctly checked box still
    # verifies as empty and fails the submit.
    return await page.evaluate(
        """
        ({ fieldId, fieldPath, selector }) => {
            const byPath = fieldPath
                ? document.querySelector(`[data-field-path="${CSS.escape(fieldPath)}"]`) : null;
            const container = byPath
                || document.querySelector(`[data-field-path="${CSS.escape(fieldId)}"]`);
            let input = container?.querySelector('input[type="checkbox"]') || null;
            if (!input && selector) {
                try {
                    const selected = document.querySelector(selector);
                    if (selected?.matches?.('input[type="checkbox"]')) input = selected;
                } catch (e) {}
            }
            return input ? !!input.checked : null;
        }
        """,
        {"fieldId": field_id, "fieldPath": _durable_field_path(field_id), "selector": selector},
    )


_RENDERED_DATE_RE = re.compile(
    r"^\s*(?:\d{1,2}[/-]\d{1,2}[/-]\d{2,4}|\d{4}-\d{2}-\d{2})\s*$")


def _looks_like_rendered_date(value) -> bool:
    return bool(_RENDERED_DATE_RE.match(str(value or "")))


def _verification_match(ftype: str, expected, actual) -> bool:
    if actual is None:
        return False
    if ftype == "number":
        try:
            return float(str(expected).strip()) == float(str(actual).strip())
        except Exception:
            return _norm_value(expected) == _norm_value(actual)
    if ftype == "date":
        return _date_values_match(expected, actual)
    if ftype in ("text", "textarea") and _looks_like_rendered_date(actual):
        # The extractor types a react-datepicker as "text", so the filler routes
        # it to _fill_date and the control ends up holding "09/07/2026" while the
        # answer said "Immediately". Comparing those as strings fails a fill that
        # is actually correct. Compare as dates when the control clearly holds one.
        if _date_values_match(expected, actual):
            return True
    if ftype == "checkbox":
        return bool(actual) == truthy(expected)
    if ftype == "multi_checkbox":
        exp = {_norm_value(v) for v in (expected if isinstance(expected, list) else [expected])}
        act = {_norm_value(v) for v in (actual if isinstance(actual, list) else [actual])}
        return exp.issubset(act)
    if ftype == "combobox":
        exp = _norm_value(expected)
        act = _norm_value(actual)
        if not act:
            return False
        if exp == act or exp in act or act in exp:
            return True
        terms = [t for t in re.split(r"[^a-z0-9+-]+", exp) if t and t not in {"the", "and", "or", "in", "of", "united", "states"}]
        return any(t in act for t in terms)
    return _norm_value(expected) == _norm_value(actual)


def _norm_value(value) -> str:
    if isinstance(value, bool):
        return "true" if value else "false"
    if isinstance(value, list):
        return " | ".join(_norm_value(v) for v in value)
    return re.sub(r"\s+", " ", str(value or "").strip()).lower()


def _short_value(value) -> str:
    if isinstance(value, list):
        value = " | ".join(str(v) for v in value)
    return str(value if value is not None else "")[:60]


def _print_verify(verify: dict) -> None:
    print(f"\nVerification: {verify['summary']}")
    for c in verify["checks"]:
        if not c["pass"]:
            print(f"  MISMATCH {c['id']}: expected={c['expected']!r} actual={c['actual']!r}")


def _print_summary(result: dict) -> None:
    filled = len(result["filled"])
    skipped = len(result["skipped"])
    errors = len([e for e in result["errors"] if "error" in e])
    print(f"\nFill complete: {filled} filled, {skipped} skipped, {errors} errors")
    for e in result["errors"]:
        if "error" in e:
            print(f"  ERROR {e['id']}: {e['error']}")


async def main() -> None:
    if len(sys.argv) < 2 or sys.argv[1] in {"-h", "--help"}:
        print(HELP_TEXT)
        if len(sys.argv) < 2:
            sys.exit(1)
        return
    if len(sys.argv) > 3:
        print(HELP_TEXT)
        sys.exit(1)

    payload_path = Path(sys.argv[1])
    output_dir = Path(sys.argv[2]) if len(sys.argv) > 2 else payload_path.parent

    result = await fill(payload_path, output_dir)
    if any("error" in e for e in result["errors"]):
        sys.exit(1)


if __name__ == "__main__":
    asyncio.run(main())
