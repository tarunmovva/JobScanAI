HELP_TEXT = """Lever form filler

Usage:
  python -m job_application_automator.lever_form_filler <payload.json> [output_dir]

Arguments:
  payload.json  Edited fill_payload.json generated by lever_form_extractor.py.
  output_dir    Optional directory for fill_result.json and screenshots.

Behavior:
  Opens the Lever application in the shared Chrome CDP profile, uploads files, fills fields,
  pauses for CAPTCHA when required, submits, and leaves the tab open if CAPTCHA blocks submission.
"""


NAV_TIMEOUT = 25_000
RENDER_WAIT = 3_000
FIELD_DELAY = 100  # ms between fills


def _write_result(output_dir: Path, result: dict) -> None:
    out_file = output_dir / "fill_result.json"
    out_file.write_text(json.dumps(result, indent=2, ensure_ascii=False), encoding="utf-8")


async def fill(payload_path: Path, output_dir: Path) -> dict:
    """Crash guard: any unhandled exception still writes fill_result.json so
    Go/Electron always find a submission status (mirrors greenhouse)."""
    try:
        return await _fill_inner(payload_path, output_dir)
    except Exception as exc:
        reason = f"{type(exc).__name__}: {exc}"
        result = {
            "platform": "lever",
            "apply_url": "",
            "filled_at": datetime.now().isoformat(timespec="seconds"),
            "filled": [], "skipped": [],
            "errors": [{"id": "_fatal", "error": reason}],
            "submission": {"status": "error", "reason": reason},
            "tab_left_open": False,
        }
        try:
            result["apply_url"] = json.loads(payload_path.read_text(encoding="utf-8")).get("apply_url", "")
        except Exception:
            pass
        _write_result(output_dir, result)
        print(f"Fatal filler error — wrote error result: {reason}", file=sys.stderr)
        return result


async def _fill_inner(payload_path: Path, output_dir: Path) -> dict:
    log = FillLog("lever", job_ref_from(payload_path), output_dir)
    payload = json.loads(payload_path.read_text(encoding="utf-8"))
    apply_url: str = payload["apply_url"]
    # See the note in ashby_form_filler: inject before binding.
    _cover_fields = inject_cover_letter(payload, output_dir)
    answers: dict = payload.get("answers", {})

    result = {
        "platform": "lever",
        "apply_url": apply_url,
        "filled_at": datetime.now().isoformat(timespec="seconds"),
        "filled": [],
        "skipped": [],
        "errors": [],
    }

    async with async_playwright() as pw, close_tab_on_unattended_crash() as tab_guard:
        session = await open_cdp_page(
            pw, viewport={"width": 1366, "height": 900},
            tab_stage="fill",
            tab_text=tab_tag.tab_text(
                (payload.get("job_context") or {}).get("company") or "",
                (payload.get("job_context") or {}).get("title") or "",
            ),
        )
        tab_guard.watch(session)
        page = session.page

        # Capture Lever API response to detect submission outcome
        _api_response: dict = {}
        async def _on_response(resp):
            if "lever.co" in resp.url and "/apply" in resp.url and resp.request.method == "POST":
                try:
                    body = await resp.body()
                    req_post = resp.request.post_data or ""
                    _api_response["status"] = resp.status
                    _api_response["body"] = body[:800].decode("utf-8", errors="replace")
                    _api_response["request_fields"] = {
                        k: v[:40] for k, v in
                        (pair.split("=", 1) if "=" in pair else (pair, "") for pair in req_post[:2000].split("&"))
                        if k
                    }
                except Exception:
                    pass
        page.on("response", _on_response)

        log("nav.start", url=apply_url)
        try:
            await page.goto(apply_url, wait_until="domcontentloaded", timeout=NAV_TIMEOUT)
            log("nav.done", elapsed_s=log.elapsed_s())
        except Exception as exc:
            result["errors"].append(f"navigate: {exc}")
            # Broken failure — no page to complete manually; close and record.
            log("nav.failed", err=str(exc))
            result["submission"] = {"status": "nav_failed", "reason": f"navigate: {exc}"}
            result["tab_left_open"] = False
            await session.cleanup()
            _write_result(output_dir, result)
            return result

        form_found = True
        try:
            await page.wait_for_selector("#application-form", timeout=10_000)
        except Exception:
            result["errors"].append("form not found")
            form_found = False

        await page.wait_for_timeout(RENDER_WAIT)

        # Load field definitions from extracted_fields.json if available
        extracted_path = payload_path.parent / "extracted_fields.json"
        if extracted_path.exists():
            extracted = json.loads(extracted_path.read_text(encoding="utf-8"))
            fields = {f["id"]: f for f in extracted.get("fields", [])}
        else:
            fields = {}

        # Pass 1: upload resume first, then wait for analysis to finish
        for field_id, value in answers.items():
            if value == "" or value is None:
                continue
            field_def = fields.get(field_id, {})
            ftype = field_def.get("type", _guess_type(field_id, value))
            if ftype != "file":
                continue
            selector = field_def.get("selector", "")
            ok, err = await _fill_field(page, field_id, ftype, value, selector, field_def)
            log("fill.field", id=field_id, type=ftype, ok=ok, err=None if ok else err)
            if ok:
                result["filled"].append(field_id)
                await _wait_for_resume_analysis(page)
            else:
                result["errors"].append({"id": field_id, "error": err})

        # Screenshot after resume upload (before CAPTCHA pause)
        try:
            ts = datetime.now().strftime("%H%M%S")
            await page.screenshot(path=str(output_dir / f"filled_{ts}.png"), full_page=True)
        except Exception:
            pass

        # Pause for CAPTCHA BEFORE filling other fields.
        # reCAPTCHA success triggers a React re-render that resets controlled inputs,
        # so we solve it first while the form is mostly empty, then fill + submit.
        import sys as _sys
        if _sys.stdin.isatty():
            # Interactive terminal — wait for user to press Enter after solving
            print("\n=== CAPTCHA ===")
            print("Solve the CAPTCHA in the browser, then press ENTER here to fill + submit.")
            try:
                await asyncio.get_event_loop().run_in_executor(None, input)
            except Exception:
                pass
        else:
            # Non-interactive (subprocess): CDP Chrome does not trigger CAPTCHA — skip immediately
            await asyncio.sleep(0.5)

        # Pass 2: fill all non-file, non-location fields AFTER CAPTCHA
        location_value = None
        for field_id, value in answers.items():
            if value == "" or value is None:
                result["skipped"].append({"id": field_id, "reason": "empty value"})
                log("skip", id=field_id, reason="empty value")
                continue

            field_def = fields.get(field_id, {})
            skip_reason = _should_skip_answer(field_id, value, answers, field_def)
            if skip_reason:
                result["skipped"].append({"id": field_id, "reason": skip_reason})
                continue

            ftype = field_def.get("type", _guess_type(field_id, value))
            if ftype == "file":
                continue  # already done in pass 1
            if field_id == "location":
                location_value = value  # fill last, right before submit
                continue

            selector = field_def.get("selector", "")
            ok, err = await _fill_field(page, field_id, ftype, value, selector, field_def)
            log("fill.field", id=field_id, type=ftype, ok=ok, err=None if ok else err)
            if ok:
                result["filled"].append(field_id)
            else:
                result["errors"].append({"id": field_id, "error": err})

            await page.wait_for_timeout(FIELD_DELAY)

        # In-session verification (while form is filled, before location)
        verify = await _verify_filled(page, fields, answers)
        result["verification"] = verify
        _print_verify(verify)
        log("verify.done", checks=len(verify.get("checks") or []),
            failed=len([c for c in verify.get("checks") or [] if not c.get("pass")]))

        # Screenshot after fill
        try:
            ts = datetime.now().strftime("%H%M%S")
            await page.screenshot(path=str(output_dir / f"filled_{ts}.png"), full_page=True)
        except Exception:
            pass

        # Fill location LAST — right before submit so no subsequent blur can clear it.
        # Skip if Lever's resume analysis already auto-filled it (proper widget state).
        # Overwriting that value causes the autocomplete widget to clear on next blur.
        existing_location = await page.evaluate("""
            () => (document.querySelector("input[name='location']") || {}).value || ""
        """)
        if location_value and not existing_location.strip():
            ok, err = await _fill_field(page, "location", "location", location_value, "", {})
            if ok:
                result["filled"].append("location")
            else:
                result["errors"].append({"id": "location", "error": err})

        if not submit_enabled():
            # Fill-and-verify only. Lever had no gate at all before this, so the
            # only way to exercise this filler was to send a real application.
            print("JOB_AUTOMATOR_SUBMIT=0 — filled but not submitted.")
            result["submission"] = {"status": "not_submitted",
                                    "reason": "JOB_AUTOMATOR_SUBMIT=0"}
            result["tab_left_open"] = False
            if unattended_run():
                await session.cleanup()
            _write_result(output_dir, result)
            _print_summary(result)
            return result

        # Auto-click submit immediately (before any React re-render can clear fields)
        # Use JS .click() not Playwright .click() — Playwright's click fires mousedown
        # which blurs the location input before the click, causing the autocomplete
        # widget's onBlur handler to clear the location value before validation.
        submitted = False
        for js_sel in ["#btn-submit", "button[type='submit']", "button[type=submit]"]:
            try:
                clicked = await page.evaluate(f"""
                () => {{
                    const btn = document.querySelector({json.dumps(js_sel)});
                    if (!btn) return false;
                    btn.click();
                    return true;
                }}
                """)
                if clicked:
                    submitted = True
                    print(f"Clicked submit (JS): {js_sel}")
                    break
            except Exception:
                pass
        if not submitted:
            # fallback to Playwright click
            for sel in ["button[type='submit']", "button[type=submit]", "#btn-submit"]:
                try:
                    btn = page.locator(sel).first
                    if await btn.is_visible(timeout=2000):
                        await btn.click()
                        submitted = True
                        print(f"Clicked submit (PW): {sel}")
                        break
                except Exception:
                    pass
        if not submitted:
            print("Submit button not found — please click manually.")

        try:
            # Wait for navigation (success page) or at most 8s
            await page.wait_for_load_state("networkidle", timeout=8000)
        except Exception:
            await asyncio.sleep(3)

        # Log actual API response
        if _api_response:
            status = _api_response.get("status", "?")
            body = _api_response.get("body", "")
            req_fields = _api_response.get("request_fields", {})
            print(f"API response: HTTP {status}")
            print(f"  body: {body[:150]!r}")
            print(f"  sent fields: {list(req_fields.keys())[:20]}")
            result["api_response"] = {"status": status, "body_start": body[:300], "sent_fields": list(req_fields.keys())}
        else:
            print("API response: not captured (no POST intercepted)")

        try:
            await page.screenshot(path=str(output_dir / "submitted.png"), full_page=True)
        except Exception:
            pass

        # Lever confirms in place; give a late confirmation a moment to appear
        # rather than paying a full recovery run to discover it.
        submission = await settle_submission(
            lambda: _detect_submission_state(page, submitted, _api_response, form_found))
        result["submission"] = submission
        log("submit.state", status=submission["status"], reason=submission.get("reason"))
        if submission["status"] != "submitted":
            result["errors"].append({
                "id": "_submission",
                "error": f"{submission['status']}: {submission['reason']}",
            })

            # AI recovery: agent fixes the live tab and submits. The response
            # listener stays attached, so the agent's submit POST lands in
            # _api_response and re-detection sees the real API outcome.
            async def _recovery_detect() -> bool:
                detected = await _detect_submission_state(page, True, _api_response, form_found)
                return detected.get("status") == "submitted"

            recovered = await attempt_recovery(
                platform="lever", apply_url=apply_url, payload=payload,
                result=result, output_dir=output_dir,
                failure={
                    "status": submission["status"],
                    "reason": submission.get("reason", ""),
                    "errors": result["errors"],
                    "verification": result.get("verification"),
                    # The controls Lever's own validation rejected, with their
                    # names and browser validationMessage. Already collected by
                    # _submit_state; without forwarding it the recovery agent got
                    # only "1 invalid controls remain" and had to hunt for which.
                    "invalid_controls": submission.get("invalid"),
                    "skipped": result.get("skipped"),
                },
                page=page, detect=_recovery_detect, log=log,
            )
            if recovered:
                submission = apply_recovery(result, recovered)
        # Keep the tab open on any failure so the user can finish manually;
        # close only on success or when the form was never found.
        keep_tab_open = should_keep_tab_open(submission["status"], form_found=form_found)
        result["tab_left_open"] = keep_tab_open
        if keep_tab_open:
            result["tab_left_open_reason"] = submission["status"]

        # Close tab on success.
        try:
            if submission["status"] == "submitted":
                await page.close()
                print("Tab closed on success.")
                result["tab_closed"] = True
        except Exception:
            pass

        if keep_tab_open:
            log("tab.policy", keep_open=True, reason=submission["status"])
            # A tab left open is one the user is expected to finish by hand,
            # so it must stop claiming it is still being filled.
            await tab_tag.apply_stage(
                page, tab_tag.stage_for_status(submission["status"]))
        else:
            await session.cleanup()

    _write_result(output_dir, result)
    log("result.written", status=(result.get("submission") or {}).get("status"), elapsed_s=log.elapsed_s())
    _print_summary(result)
    return result


async def _captcha_puzzle_visible(page: Page) -> bool:
    """True when an hCaptcha/reCAPTCHA CHALLENGE is on screen.

    Deliberately does not match the plain "I'm not a robot" checkbox — that is
    one click and the filler handles it. This looks for the challenge overlay,
    the thing only a person can complete.
    """
    try:
        return bool(await page.evaluate(
            r"""() => {
                const visible = (el) => {
                    if (!el) return false;
                    const r = el.getBoundingClientRect();
                    const s = getComputedStyle(el);
                    return r.width > 40 && r.height > 40 && s.visibility !== 'hidden' && s.display !== 'none';
                };
                const frames = Array.from(document.querySelectorAll('iframe'));
                for (const f of frames) {
                    const src = String(f.getAttribute('src') || '');
                    const title = String(f.getAttribute('title') || '').toLowerCase();
                    const isChallenge =
                        /hcaptcha\.com\/captcha/i.test(src) && /challenge/i.test(src)
                        || /google\.com\/recaptcha\/api2\/bframe/i.test(src)
                        || title.includes('challenge');
                    if (isChallenge && visible(f)) return true;
                    // A captcha iframe large enough to sit over the form blocks
                    // submission even when it has not rendered a visible
                    // challenge overlay yet. One recorded run reported exactly
                    // this — "hCaptcha iframe blocks page interactions but
                    // exposes no usable checkbox or challenge" — fell through as
                    // not_confirmed, and spent 107s in fix-mode recovery on
                    // something no agent can clear.
                    const isCaptchaFrame = /hcaptcha\.com|google\.com\/recaptcha/i.test(src);
                    if (isCaptchaFrame && visible(f)) {
                        const r = f.getBoundingClientRect();
                        if (r.width > 220 && r.height > 220) return true;
                    }
                }
                // hCaptcha renders its puzzle host inline on some pages.
                return Array.from(document.querySelectorAll(
                    '[class*="challenge"], [id*="challenge"]'))
                    .some((el) => visible(el) && /captcha/i.test(el.className + ' ' + el.id));
            }"""))
    except Exception:
        return False


# The confirmation matcher now lives in submission_signals and is shared with
# the greenhouse and ashby fillers. Three private copies had drifted: this one
# matched seven phrasings, greenhouse matched four fixed substrings and missed
# "your application has been received", which is what greenhouse itself prints.
_confirmation_text = confirmation_text


async def _detect_submission_state(page: Page, clicked_submit: bool, api_response: dict,
                                   form_was_present: bool = True) -> dict:
    """Classify Lever submission without relying on one company's success text."""
    if not clicked_submit:
        return {"status": "submit_button_not_found", "reason": "no submit button was clicked"}

    current_url = page.url
    url_l = current_url.lower()
    if any(kw in url_l for kw in ("thank", "success", "confirmation", "submitted", "complete")):
        return {"status": "submitted", "reason": f"success URL: {current_url}"}

    status = api_response.get("status")
    body = str(api_response.get("body", ""))
    body_l = body.lower()
    if "captcha" in body_l:
        return {"status": "blocked_captcha", "reason": f"Lever apply API CAPTCHA response: {body[:160]}"}

    # A VISIBLE puzzle challenge is a different outcome from a failed fill: the
    # form is complete and correct, and a person has to clear the challenge. It
    # was landing as not_confirmed/validation_failed, which is indistinguishable
    # from a broken fill — nearly a quarter of recorded lever runs, each of which then spent
    # a full AI recovery attempt on a puzzle the agent is explicitly told it
    # cannot solve.
    if await _captcha_puzzle_visible(page):
        return {"status": "blocked_captcha_puzzle",
                "reason": "a CAPTCHA puzzle challenge is on screen — the form is filled, "
                          "it needs a person to clear the challenge and submit"}
    if isinstance(status, int):
        if 200 <= status < 300 and not any(term in body_l for term in ("error", "invalid", "captcha", "required")):
            return {"status": "submitted", "reason": f"Lever apply API HTTP {status}"}
        if status >= 400:
            return {"status": "api_failed", "reason": f"Lever apply API HTTP {status}: {body[:160]}"}

    try:
        state = await page.evaluate(
            """
            () => {
                const form = document.querySelector('#application-form');
                const controls = document.querySelectorAll(
                    '#application-form input:not([type="hidden"]), #application-form textarea, #application-form select'
                );
                const invalid = Array.from(controls).filter((el) => {
                    if (el.disabled) return false;
                    const ariaInvalid = el.getAttribute('aria-invalid') === 'true';
                    const nativeInvalid = typeof el.checkValidity === 'function' && !el.checkValidity();
                    return ariaInvalid || nativeInvalid;
                });
                const labelFor = (el) => {
                    let container = el.closest('.application-question, label, [data-qa]');
                    if (!container) container = el.parentElement;
                    return (container?.innerText || '').replace(/\\s+/g, ' ').trim().slice(0, 180);
                };
                const bodyText = (document.body?.innerText || '').replace(/\\s+/g, ' ').trim().slice(0, 1200);
                return {
                    hasForm: !!form,
                    controlCount: controls.length,
                    invalidCount: invalid.length,
                    invalid: invalid.slice(0, 10).map((el) => ({
                        name: el.getAttribute('name') || el.id || '',
                        type: el.type || el.tagName,
                        label: labelFor(el),
                        message: el.validationMessage || '',
                        value: (el.value || '').slice(0, 80),
                    })),
                    bodyText,
                };
            }
            """
        )
        # A dead posting has no form either. "Disappeared after submit" and
        # "never existed because the job is gone" look identical from here,
        # and this branch recorded a real 404 as a submitted application.
        gone = posting_gone(state.get("bodyText"))
        if gone:
            return {"status": "posting_closed", "reason": f"posting is gone: {gone!r}"}
        if not state.get("hasForm") or state.get("controlCount", 0) == 0:
            if not form_was_present:
                # The form was already missing BEFORE the submit, so its
                # absence now is not evidence of anything.
                return {"status": "form_not_found",
                        "reason": "no application form was ever present on this page"}
            return {"status": "submitted", "reason": "application form disappeared after submit"}

        # Lever can confirm in PLACE: it prints "Application submitted!" without
        # redirecting to /thanks, without an API response we captured, and
        # without removing the form. All three detectors above miss that, so a
        # finished application was reported not_confirmed and handed to recovery
        # — which found the confirmation already on screen and said so. bodyText
        # was already being collected here and simply never read.
        #
        # This matters beyond the wasted run: fix-mode recovery is told to
        # "complete this application and submit it", so a detector that cannot
        # see success is one step away from submitting twice.
        confirmation = _confirmation_text(state.get("bodyText"))
        if confirmation:
            return {"status": "submitted", "reason": f"confirmation on page: {confirmation!r}"}
        if state.get("invalidCount", 0) > 0:
            details = state.get("invalid", [])
            return {
                "status": "validation_failed",
                "reason": f"{state['invalidCount']} invalid controls remain",
                "invalid": details,
            }
    except Exception:
        pass

    return {"status": "not_confirmed", "reason": "no success URL or successful Lever API response captured"}


def _should_skip_answer(field_id: str, value, answers: dict, field_def: dict) -> str:
    """Skip answers that make optional Lever sections conditionally required."""
    if field_id == "eeo[disability]" and not field_def.get("required"):
        has_signature = bool(str(answers.get("eeo[disabilitySignature]", "")).strip())
        has_date = bool(str(answers.get("eeo[disabilitySignatureDate]", "")).strip())
        if value and not (has_signature and has_date):
            return "optional disability self-ID skipped; payload has no signature/date"
    return ""


async def _wait_for_resume_analysis(page: Page) -> None:
    """Wait for Lever's resume analysis spinner to disappear before filling fields."""
    try:
        await page.wait_for_selector("text=Analyzing", timeout=6000)
    except Exception:
        return  # spinner never appeared — resume uploaded instantly or no analysis
    try:
        await page.wait_for_selector("text=Analyzing", state="hidden", timeout=30000)
        await page.wait_for_timeout(800)
    except Exception:
        pass


async def _fill_field(
    page: Page,
    field_id: str,
    ftype: str,
    value,
    selector: str,
    field_def: dict,
) -> tuple[bool, str]:
    """Fill a single field. Returns (success, error_message)."""
    try:
        if ftype == "file":
            return await _fill_file(page, field_id, value, selector)

        if ftype == "select":
            return await _fill_select(page, field_id, value, selector, field_def)

        if ftype == "radio":
            return await _fill_radio(page, field_id, value, selector, field_def)

        if ftype == "checkbox":
            if selector.strip().lower().startswith("select"):
                select_value = value[0] if isinstance(value, list) and value else value
                return await _fill_select(page, field_id, select_value, selector, field_def)
            return await _fill_checkbox(page, field_id, value, selector)

        if field_id == "location":
            # Always use autocomplete-aware filler; _fill_text leaves the widget
            # state inconsistent and the value gets cleared on the next blur.
            return await _fill_location(page, value)

        if ftype in ("text", "email", "tel", "url", "textarea"):
            return await _fill_text(page, field_id, ftype, value, selector)

        return False, f"unknown type {ftype}"

    except Exception as exc:
        return False, str(exc)


async def _fill_location(page: Page, value: str) -> tuple[bool, str]:
    """Fill Lever's location autocomplete field — type, wait for dropdown, select first option."""
    sel = 'input[name="location"], input.location-input, input[data-qa="location-input"]'
    el = page.locator(sel).first
    if not await el.count():
        return False, "location input not found"

    await el.click()
    await el.fill("")
    await page.wait_for_timeout(200)

    # Type first few chars to trigger autocomplete, then wait for suggestions
    short = value.split(",")[0].strip()  # e.g. "Austin"
    await el.type(short, delay=60)
    await page.wait_for_timeout(1500)

    # Try ArrowDown + Enter to select first suggestion (most reliable for autocompletes)
    await el.press("ArrowDown")
    await page.wait_for_timeout(300)
    actual_after_arrow = await el.input_value()
    if actual_after_arrow and actual_after_arrow != short:
        # Suggestion populated — press Enter to confirm
        await el.press("Enter")
        await page.wait_for_timeout(300)
        return True, f"selected autocomplete: {actual_after_arrow!r}"

    # Try clicking first visible suggestion
    for opt_sel in [
        ".location-item",
        "[data-qa='location-item']",
        ".momentum-body li",
        "[class*='location-suggestion']",
        "[class*='autocomplete'] li",
    ]:
        opts = page.locator(opt_sel)
        if await opts.count() > 0:
            await opts.first.click()
            await page.wait_for_timeout(300)
            return True, "clicked suggestion"

    # Final fallback: set visible input + selectedLocation hidden input via JS.
    # Setting selectedLocation prevents the widget's onBlur handler from clearing
    # the visible input value when no geocoded suggestion was selected.
    await page.evaluate(f"""
    () => {{
        const input = document.querySelector('input[name="location"], input.location-input');
        if (!input) return;
        const setter = Object.getOwnPropertyDescriptor(window.HTMLInputElement.prototype, 'value')?.set;
        if (setter) setter.call(input, {json.dumps(value)});
        else input.value = {json.dumps(value)};
        input.dispatchEvent(new Event('input', {{ bubbles: true }}));
        input.dispatchEvent(new Event('change', {{ bubbles: true }}));
        // Populate selectedLocation so widget considers a selection committed
        const sel = document.querySelector('input[name="selectedLocation"]');
        if (sel) sel.value = {json.dumps(value)};
    }}
    """)
    await page.wait_for_timeout(500)
    return True, "set via JS dispatch, no suggestion selected"


async def _fill_text(page: Page, field_id: str, ftype: str, value: str, selector: str) -> tuple[bool, str]:
    tag = "textarea" if ftype == "textarea" else "input"
    str_value = str(value)
    for sel in _candidate_selectors(tag, field_id, selector):
        el = page.locator(sel).first
        if not await el.count():
            continue
        try:
            await el.scroll_into_view_if_needed(timeout=3000)
            await el.click(timeout=3000)
            # Use triple-click to select all existing text, then type() char-by-char.
            # type() fires keydown/keypress/input/keyup per character — React's synthetic
            # event system picks these up reliably. fill() sets DOM value but misses
            # React's fiber state update in some Lever form configurations.
            await el.press("Control+a")
            await page.keyboard.type(str_value, delay=8)
            return True, ""
        except Exception:
            # JS fallback for overlaid/disabled inputs
            try:
                proto = "HTMLTextAreaElement" if ftype == "textarea" else "HTMLInputElement"
                ok = await page.evaluate(f"""
                (sel) => {{
                    const el = document.querySelector(sel);
                    if (!el) return false;
                    const setter = Object.getOwnPropertyDescriptor(window.{proto}.prototype, 'value')?.set
                        || Object.getOwnPropertyDescriptor(window.HTMLInputElement.prototype, 'value')?.set
                        || Object.getOwnPropertyDescriptor(window.HTMLTextAreaElement.prototype, 'value')?.set;
                    if (setter) setter.call(el, {json.dumps(str_value)});
                    else el.value = {json.dumps(str_value)};
                    el.dispatchEvent(new Event('input', {{ bubbles: true }}));
                    el.dispatchEvent(new Event('change', {{ bubbles: true }}));
                    return true;
                }}
                """, sel)
                if ok:
                    return True, "filled via JS"
            except Exception:
                pass
    return False, f"selector not found: {selector!r}"


async def _fill_file(page: Page, field_id: str, value: str, selector: str) -> tuple[bool, str]:
    path = Path(value)
    if not path.exists():
        return False, f"file not found: {value}"
    for sel in [selector, f'input[type="file"][name="{field_id}"]', 'input[type="file"]']:
        if not sel:
            continue
        el = page.locator(sel).first
        if await el.count():
            await el.set_input_files(str(path))
            return True, ""
    return False, f"file input not found: {selector!r}"


async def _fill_card_select_by_question(page: Page, question_label: str, value: str) -> str | None:
    """Select a custom Lever card dropdown by its nearest question label."""
    return await page.evaluate(r"""
    (args) => {
        const form = document.getElementById('application-form') || document.body;
        const normalize = (s) => (s || '')
            .replace(/[✱*]+/g, '')
            .replace(/\s+/g, ' ')
            .trim()
            .toLowerCase();
        const labelNeedle = normalize(args.label);
        const valueNeedle = normalize(args.value);

        const choose = (sel) => {
            const validOpts = Array.from(sel.options)
                .filter((opt) => normalize(opt.text) && normalize(opt.text) !== 'select...');
            const passes = [
                (opt) => normalize(opt.text) === valueNeedle || normalize(opt.value) === valueNeedle,
                (opt) => {
                    const t = normalize(opt.text);
                    return t.includes(valueNeedle) && valueNeedle.length >= t.length - 4;
                },
                (opt) => {
                    const t = normalize(opt.text);
                    return t.includes(valueNeedle) || valueNeedle.includes(t);
                },
            ];
            for (const pass of passes) {
                for (const opt of validOpts) {
                    if (pass(opt)) {
                        sel.value = opt.value;
                        sel.dispatchEvent(new Event('input', {bubbles: true}));
                        sel.dispatchEvent(new Event('change', {bubbles: true}));
                        return opt.text;
                    }
                }
            }
            return null;
        };

        const labelEls = Array.from(form.querySelectorAll('*')).filter((el) =>
            !el.querySelector('input, select, textarea') && normalize(el.textContent) === labelNeedle
        );
        for (const labelEl of labelEls) {
            let container = labelEl;
            while (container && container !== form) {
                const selects = Array.from(container.querySelectorAll('select'));
                if (selects.length === 1) {
                    const picked = choose(selects[0]);
                    if (picked) return picked;
                }
                container = container.parentElement;
            }
        }

        for (const container of form.querySelectorAll('li.application-question, div.application-question')) {
            const selects = Array.from(container.querySelectorAll('select'));
            if (selects.length === 1 && normalize(container.textContent).includes(labelNeedle)) {
                const picked = choose(selects[0]);
                if (picked) return picked;
            }
        }
        return null;
    }
    """, {"label": question_label, "value": value})


async def _fill_select(page: Page, field_id: str, value: str, selector: str, field_def: dict = None) -> tuple[bool, str]:
    if field_id.startswith("cards[") and field_def:
        question_label = (field_def.get("label") or "").strip()
        if question_label:
            matched = await _fill_card_select_by_question(page, question_label, value)
            if matched:
                return True, f"label-based select: {matched!r}"

    # For cards[UUID][fieldN] selects, UUID changes each page visit — use label-based search
    if field_id.startswith("cards[") and field_def:
        question_label = (field_def.get("label") or "").strip()
        if question_label:
            matched = await page.evaluate("""
            (args) => {
                const form = document.getElementById('application-form') || document.body;
                for (const sel of form.querySelectorAll('select')) {
                    let container = sel.parentElement;
                    while (container && container !== form) {
                        if ((container.textContent || '').includes(args.label)) {
                            const needle = args.value.toLowerCase();
                            // 1st pass: exact case-insensitive match
                            for (const opt of sel.options) {
                                if (opt.text.toLowerCase() === needle || opt.value.toLowerCase() === needle) {
                                    sel.value = opt.value;
                                    sel.dispatchEvent(new Event('change', {bubbles: true}));
                                    return opt.text;
                                }
                            }
                            // 2nd pass: substring match (avoid short needle matching longer options first)
                            for (const opt of sel.options) {
                                if (opt.text.toLowerCase().includes(needle) && needle.length >= opt.text.toLowerCase().length - 4) {
                                    sel.value = opt.value;
                                    sel.dispatchEvent(new Event('change', {bubbles: true}));
                                    return opt.text;
                                }
                            }
                            // 3rd pass: loose substring
                            for (const opt of sel.options) {
                                if (opt.text.toLowerCase().includes(needle) || needle.includes(opt.text.toLowerCase())) {
                                    sel.value = opt.value;
                                    sel.dispatchEvent(new Event('change', {bubbles: true}));
                                    return opt.text;
                                }
                            }
                            break;
                        }
                        container = container.parentElement;
                    }
                }
                return null;
            }
            """, {"label": question_label, "value": value})
            if matched:
                return True, f"label-based select: {matched!r}"

    for sel in [selector, f'select[name="{field_id}"]']:
        if not sel:
            continue
        el = page.locator(sel).first
        if await el.count():
            try:
                await el.select_option(label=value)
                return True, ""
            except Exception:
                # Fuzzy match: exact first, then substring — avoids short needle hitting longer option
                matched = await page.evaluate(f"""
                (sel) => {{
                    const el = document.querySelector(sel);
                    if (!el) return null;
                    const needle = {json.dumps(str(value).lower())};
                    // exact
                    for (const opt of el.options) {{
                        if (opt.text.toLowerCase() === needle || opt.value.toLowerCase() === needle) {{
                            el.value = opt.value;
                            el.dispatchEvent(new Event('change', {{bubbles:true}}));
                            return opt.text;
                        }}
                    }}
                    // substring (needle must cover most of option text)
                    for (const opt of el.options) {{
                        const t = opt.text.toLowerCase();
                        if (t.includes(needle) && needle.length >= t.length - 4) {{
                            el.value = opt.value;
                            el.dispatchEvent(new Event('change', {{bubbles:true}}));
                            return opt.text;
                        }}
                    }}
                    // loose
                    for (const opt of el.options) {{
                        const t = opt.text.toLowerCase();
                        if (t.includes(needle) || needle.includes(t)) {{
                            el.value = opt.value;
                            el.dispatchEvent(new Event('change', {{bubbles:true}}));
                            return opt.text;
                        }}
                    }}
                    return null;
                }}
                """, sel)
                if matched:
                    return True, f"fuzzy select: {matched!r}"
    return False, f"select not found: {selector!r}"


async def _fill_radio(page: Page, field_id: str, value: str, selector: str, field_def: dict) -> tuple[bool, str]:
    """Click the radio option whose label or value matches `value`."""
    # For card fields (cards[UUID][fieldN]), UUID changes each page visit.
    # Use label-based DOM search instead of stale UUID selector.
    if field_id.startswith("cards["):
        question_label = field_def.get("label", "")
        if question_label:
            result = await page.evaluate(f"""
            () => {{
                const needle = {json.dumps(question_label.strip())};
                const val = {json.dumps(str(value).lower())};
                // Find any leaf text node in the form that exactly matches the question label
                const form = document.getElementById('application-form') || document.body;
                // Gather all text-bearing leaf elements
                const allEls = Array.from(form.querySelectorAll('*'));
                let labelEl = null;
                for (const el of allEls) {{
                    // Only look at leaf-ish nodes (no radio/input children that would pollute textContent)
                    const txt = el.textContent.trim().replace(/[✱*]+$/, '').trim();
                    if (txt === needle && el.querySelectorAll('input,select,textarea').length === 0) {{
                        labelEl = el;
                        break;
                    }}
                }}
                if (!labelEl) return 'NO_LABEL:' + needle.substring(0,40);
                // Walk up to find the li container
                let container = labelEl.parentElement;
                while (container && container !== form) {{
                    if (container.tagName === 'LI') break;
                    container = container.parentElement;
                }}
                if (!container || container === form) return 'NO_LI';
                const radios = container.querySelectorAll('input[type=radio]');
                if (!radios.length) return 'NO_RADIOS';
                for (const r of radios) {{
                    const span = r.closest('label')?.querySelector('span.application-answer-alternative');
                    const spanText = (span?.textContent || '').trim().toLowerCase();
                    const lbl = document.querySelector('label[for="' + r.id + '"]');
                    const lblText = (lbl?.textContent || '').trim().toLowerCase();
                    if (spanText === val || lblText === val || r.value.toLowerCase() === val) {{
                        r.click();
                        return 'ok:' + r.value;
                    }}
                }}
                // No exact match — click first radio
                radios[0].click();
                return 'first:' + radios[0].value;
            }}
            """)
            if result and result.startswith(("ok:", "first:")):
                note = "" if result.startswith("ok:") else f"first-radio fallback — {result}"
                return True, note
        # label-based search failed — fall through to name-based attempts

    # Try by value attribute (works when UUID hasn't changed or for non-card radios)
    # Use JS .click() to avoid hCaptcha overlay intercepting pointer events
    for sel in [
        f'input[name="{field_id}"][value="{value}"]',
        f'input[type=radio][name="{field_id}"][value="{value}"]',
    ]:
        clicked = await page.evaluate(f"""
        () => {{
            const el = document.querySelector({json.dumps(sel)});
            if (el) {{ el.click(); return true; }}
            return false;
        }}
        """)
        if clicked:
            return True, ""

    # Try by option label text (via sibling span or label[for])
    options = field_def.get("options", [])
    for opt in options:
        opt_label = opt if isinstance(opt, str) else opt.get("label", "")
        opt_sel = opt.get("selector", "") if isinstance(opt, dict) else ""
        if opt_label.lower() == str(value).lower():
            if opt_sel:
                clicked = await page.evaluate(f"""
                () => {{
                    const el = document.querySelector({json.dumps(opt_sel)});
                    if (el) {{ el.click(); return true; }}
                    return false;
                }}
                """)
                if clicked:
                    return True, ""
            matched = await page.evaluate(f"""
            () => {{
                let found = null;
                document.querySelectorAll('input[type=radio]').forEach(r => {{
                    const lbl = document.querySelector('label[for="' + r.id + '"]');
                    if ((lbl?.textContent||'').trim().toLowerCase() === {json.dumps(str(value).lower())}) {{
                        r.click();
                        found = r.id;
                    }}
                }});
                return found;
            }}
            """)
            if matched:
                return True, ""

    # Final fallback: click first radio with this name
    clicked = await page.evaluate(f"""
    () => {{
        const el = document.querySelector({json.dumps(f'input[type=radio][name="{field_id}"]')});
        if (el) {{ el.click(); return el.value; }}
        return null;
    }}
    """)
    if clicked is not None:
        return True, f"no exact match for {value!r} — clicked first option"

    return False, f"radio not found: {field_id}"


async def _fill_checkbox(page: Page, field_id: str, value, selector: str) -> tuple[bool, str]:
    """Check or uncheck a checkbox (or check options from a list)."""
    if isinstance(value, list):
        # Multi-select: check by option label text, value attribute, or name
        errs = []
        for v in value:
            ok = await page.evaluate(f"""
            () => {{
                const normalize = (s) => (s || '')
                    .normalize('NFKD')
                    .replace(/[’‘`´]/g, "'")
                    .replace(/[“”]/g, '"')
                    .replace(/[‐‑‒–—]/g, '-')
                    .replace(/\\s+/g, ' ')
                    .trim()
                    .toLowerCase();
                const needle = normalize({json.dumps(str(v))});
                // First try: match by name attribute (specific field_id)
                const byName = document.querySelectorAll('input[type=checkbox][name="{field_id}"]');
                for (const cb of byName) {{
                    const lbl = document.querySelector('label[for="' + cb.id + '"]');
                    const lblText = normalize(lbl?.textContent);
                    const val = normalize(cb.value);
                    if (lblText === needle || val === needle || lblText.includes(needle) || needle.includes(lblText)) {{
                        if (!cb.checked) cb.click();
                        return true;
                    }}
                }}
                // Fallback: any checkbox matching label or value text
                for (const cb of document.querySelectorAll('input[type=checkbox]')) {{
                    const lbl = document.querySelector('label[for="' + cb.id + '"]');
                    const lblText = normalize(lbl?.textContent);
                    const val = normalize(cb.value || cb.name);
                    if (lblText === needle || val === needle || lblText.includes(needle) || needle.includes(lblText)) {{
                        if (!cb.checked) cb.click();
                        return true;
                    }}
                }}
                return false;
            }}
            """)
            if not ok:
                errs.append(v)
        return not errs, f"not found: {errs}" if errs else ""

    # Single checkbox
    el = page.locator(selector or f'input[name="{field_id}"]').first
    if not await el.count():
        el = page.locator(f'input[type=checkbox][name="{field_id}"]').first
    if await el.count():
        # bool("No") is True, so `if value:` checked the box for a "No" answer.
        if truthy(value):
            await el.check()
        else:
            await el.uncheck()
        return True, ""
    return False, f"checkbox not found: {field_id}"


def _candidate_selectors(tag: str, field_id: str, provided: str) -> list[str]:
    sels = []
    if provided:
        sels.append(provided)
    sels.append(f'{tag}[name="{field_id}"]')
    sels.append(f'#{field_id}')
    return sels


def _guess_type(field_id: str, value) -> str:
    if isinstance(value, list):
        return "checkbox"
    if isinstance(value, bool):
        return "checkbox"
    if "email" in field_id:
        return "email"
    if "phone" in field_id:
        return "tel"
    if field_id.startswith("urls["):
        return "url"
    if field_id.startswith("eeo["):
        # Signature and date fields are plain text inputs, not selects
        if "Signature" in field_id:
            return "text"
        return "select"
    if "resume" in field_id or "file" in field_id:
        return "file"
    return "text"


async def _verify_filled(page: Page, fields: dict, answers: dict) -> dict:
    """Check DOM values match answers while the form is still filled."""
    checks = []
    for field_id, answer in answers.items():
        if not answer or isinstance(answer, list):
            continue
        field_def = fields.get(field_id, {})
        ftype = field_def.get("type", "text")
        sel = field_def.get("selector", f'input[name="{field_id}"]')

        if ftype in ("file", "radio", "checkbox", "select"):
            continue

        actual = await page.evaluate(f"""
        () => {{
            const el = document.querySelector({json.dumps(sel)});
            return el ? (el.value || '').trim() : null;
        }}
        """)

        expected = str(answer).strip()
        # location is a geocoder autocomplete — skip exact-value check
        if field_id == "location":
            continue
        match = actual is not None and actual == expected
        checks.append({
            "id": field_id,
            "expected": expected[:60],
            "actual": (actual or "")[:60],
            "pass": match,
        })

    passed = sum(1 for c in checks if c["pass"])
    return {"checks": checks, "summary": f"{passed}/{len(checks)} value checks passed"}


def _print_verify(verify: dict) -> None:
    print(f"\nVerification: {verify['summary']}")
    for c in verify["checks"]:
        if not c["pass"]:
            print(f"  MISMATCH {c['id']}: expected={c['expected']!r} actual={c['actual']!r}")


def _print_summary(result: dict) -> None:
    filled = len(result["filled"])
    skipped = len(result["skipped"])
    errors = len(result["errors"])
    print(f"\nFill complete: {filled} filled, {skipped} skipped, {errors} errors")
    if result["errors"]:
        for e in result["errors"]:
            print(f"  ERROR: {e}")


